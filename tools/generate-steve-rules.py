"""Canonical fixed-tick recipe data and integer trigonometry, shared by host and WASM."""
from pathlib import Path
import json,math
ROOT=Path(__file__).resolve().parents[1]
def generate():
 d=json.loads((ROOT/'rules/steve-craft.json').read_text(encoding='utf-8'))
 lines=['// Generated by tools/generate-steve-rules.py. Edit rules/steve-craft.json.']
 for k,v in d.items():
  if type(v) is int:lines.append(f'pub const {k.upper()}: i64 = {v};')
 lines+=['#[derive(Clone,Copy,Debug)]','pub struct Recipe {pub id:u8,pub key:&\'static str,pub name:&\'static str,pub slot:usize,pub cooldown:usize,pub range:i64,pub radius:i64,pub life:usize,pub cap:usize,pub cost:usize,pub group:usize}',f'pub const RECIPES: [Recipe;{len(d["recipes"])}] = [']
 for r in d['recipes']:lines.append('Recipe {'+','.join(k+':'+(json.dumps(v) if isinstance(v,str) else str(v)) for k,v in r.items())+'},')
 lines+= ['];','pub const SIN: [i64;256] = '+str([round(math.sin(i*math.tau/256)*10000) for i in range(256)])+';']
 (ROOT/'native/tfm2_custom_ai/src/steve_craft_data.rs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
 (ROOT/'editor/steve-data.js').write_text('window.STEVE_RULES='+json.dumps(d,separators=(',',':'))+';\n',encoding='utf-8')
if __name__=='__main__':generate()
