"""Generate Thalassa's Rust tables, champion data, tooltips, editor data and roster entry from rules/thalassa.json.

Change numbers in the rules file and rerun; never edit the outputs by hand. `--check` only verifies.
"""
from pathlib import Path
import copy, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'rules/thalassa.json').read_text())
ID = rules['id']


def snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).upper()


lines = ['//! Generated by tools/generate-thalassa.py from rules/thalassa.json. Do not edit by hand.', '#![allow(dead_code)]', '',
         'pub const RULES_REVISION: &str = ' + json.dumps(rules['revision']) + ';',
         f'pub const MOD_POWER: [i32; 7] = {rules["modPower"]};']
for group in ['basic', 'water', 'tidePool', 'dive', 'twin', 'ult']:
    for k, v in rules[group].items():
        lines.append(f'pub const {snake(group)}_{snake(k)}: i64 = {v};')
lines.append(f'pub const FX_TOKENS: usize = {rules["fxTokens"]};')
rust = '\n'.join(lines) + '\n'

w, t, d, tw, u, b = (rules[k] for k in ['water', 'tidePool', 'dive', 'twin', 'ult', 'basic'])
sec = lambda n: f'{n / 60:g} s'
text = {
    'name': rules['name'],
    'skill': (f"Tidebound (passive): in water (her pools, or wet) she gains +{w['moveSpeedPct']}% move speed and +{w['rangePct']}% range, her harp bolts bounce to a second enemy "
              f"for {w['bouncePct']}%, and she regenerates {w['regenPerMillePerSecond'] / 10:g}% max HP a second; at full HP it becomes a shield up to {w['overhealCapPct']}% max HP. Enemies in any of her pools are slowed {w['poolSlowPct']}% (not stacking). "
              f"Tide Pool ({sec(t['cooldownTicks'])}): on land, a pool forms below her. In water, the pool she stands in surges up to {t['range']} to the target and becomes a whirlpool "
              f"({t['whirlScalePct']}% size) that pulls enemies inward once and deals {t['base']} + {t['apRatio']}% AP, slowing {t['slowPct']}% while it swirls ({sec(t['whirlTicks'])}, then it "
              f"calms into a pool); if two or more champions are caught, up to {t['bumpMaxChampions']} bump and are stunned {sec(t['bumpStunTicks'])}. A new whirlpool forms below her."),
    'skill2': (f"Dive ({sec(d['cooldownTicks'])}): in water, opens a pool up to {d['range']} away, dives into hers and surfaces from it. On land, a short slide that leaves her wet for "
               f"{sec(w['wetTicks'])}. Tide Twin ({sec(tw['cooldownTicks'])}): a water clone for {sec(tw['ticks'])} ({tw['hpPct']}% of her HP) that moves and fires harp bolts on its own at "
               f"{tw['copyPct']}%, and copies her Tide Pool and Dive to the same point when she casts them. When an ally or Thalassa is stunned within {tw['rescueRange']}, it flies to "
               f"them and becomes a pool: cleanse, "
               f"{tw['shieldBase']} + {tw['shieldApRatio']}% AP shield and {sec(tw['immuneTicks'])} crowd-control immunity. Spawned on water, it rescues Thalassa at any range, instantly, and a "
               f"tide link lets her swap places with it once when engaged, leaving a whirlpool."),
    'ult': (f"Trident of the Deep ({sec(u['cooldownTicks'])}): a slow trident with global range, steerable {u['curveMilliDegrees'] / 1000:g} degrees in total. The first enemy champion "
            f"hit is stunned {sec(u['stunTicks'])} ({sec(u['waterStunTicks'])} if thrown from water) and enemies around take {u['base']} + {u['apRatio']}% AP. It leaves a pool where it "
            f"lands (from water it flies faster and the pool is a whirlpool) and a clone of her there for {sec(u['echoTicks'])} ({u['echoHpPct']}% of her HP) that fights on its own "
            f"with harp bolts, Tide Pool and Dive at {u['echoDamagePct']}% damage."),
}

champ = copy.deepcopy(json.loads((ROOT / 'mods/tfm2_custom/champion/tfm2_custom_contender.data_champion').read_text()))
champ.update(id=ID, category=rules['category'], tags=rules['tags'], sprite='asset/tfm2_custom/champions/' + ID, anim_prefix='')
for key in ['stat', 'growth']:
    champ[key] = {k: 0 for k in champ[key]}
    champ[key].update(rules[key])
champ['attack'].update(duration=22, cooltime=b['cooldownTicks'], start_timing=12, range=b['range'],
                       effect={'type': 'TargetProjectile', 'speed': b['boltSpeed'], 'name': ID + '_bolt', 'y_offset': 0, 'applied_target': 'Enemy',
                               'applied_effects': [{'effect': {'type': 'ApAttack', 'damage': b['base'], 'attack_ratio': b['apRatio']}, 'casting_type': 'Targeting'}]})
for slot in ['skill', 'skill2', 'ult']:
    champ[slot]['description'] = '#asset/base/text/champion?description.' + ID + '.' + slot
champ['passive'] = {'passive_ref': 'tfm2_custom_ai:thalassa', 'params': {}}
champ['passive_ult'] = {'passive_ref': 'tfm2_custom_ai:ult_learned', 'params': {}}
VFX = 'asset/tfm2_custom/vfx/thalassa'
effects = (['pool', 'whirlpool', 'pool_rise', 'surge', 'bump', 'bounce', 'dive_in', 'dive_out', 'slide', 'twin_spawn', 'twin_fly', 'twin_pool', 'tide_link',
            'swap', 'rescue', 'trident_hit', 'trident_land'] + ['trident_p' + str(i) for i in range(8)] + ['twin_p' + str(i) for i in range(8)])
champ['view_effects'] = [dict(type='Animation', name='tls_' + e, anim=VFX, tag=e, z=-2 if e in ('pool', 'whirlpool', 'tide_link', 'twin_pool') else 5,
                              is_follow=False) for e in effects]
champ['view_buffs'] = [dict(type='Animated', name='tls_water', anim=VFX, tag='water_aura', z=-1),
                       dict(type='Animated', name='tls_rescued', anim=VFX, tag='rescue_shield', z=4)]
champ['view_projectiles'] = [dict(type='Animated', name=ID + '_bolt', anim=VFX, tag='bolt', z=2, repeat=True)]
art_manifest = ROOT / 'docs/thalassa-art-review/art-manifest.json'
if art_manifest.exists():
    art = json.loads(art_manifest.read_text(encoding='utf-8'))
    champ['view_effects'] = [dict(type='Animation', name='tls_' + tag, anim=spec.get('asset',VFX), tag=tag, z=spec['z'], is_follow=False)
                            for tag, spec in art['effects'].items() if spec['kind'] == 'effect']
data = json.dumps(champ, indent=2) + '\n'

roster = dict(id=ID, name=rules['name'], family='original', role='Magician', native=True,
              basicAttack=dict(name='Harp bolt', kind='ranged', range=b['range']),
              skills=[dict(slot='skill', name='Tide Pool', kinds=['Zone', 'Aoe', 'Cc'], intents=['Clear', 'Engage', 'Objective'], summary=text['skill']),
                      dict(slot='skill2', name='Dive / Tide Twin', kinds=['Dash', 'Summon', 'Shield'], intents=['Escape', 'Protect', 'Poke'], summary=text['skill2']),
                      dict(slot='ult', name='Trident of the Deep', kinds=['Projectile', 'Cc'], intents=['Engage', 'Poke'], summary=text['ult'])])

outputs = {
    ROOT / 'editor/thalassa-data.js': 'window.THALASSA_RULES = ' + json.dumps(rules, separators=(',', ':')) + ';\n',
    ROOT / 'native/tfm2_custom_ai/src/thalassa_data.rs': rust,
    ROOT / 'mods/tfm2_custom/champion' / f'{ID}.data_champion': data,
}
check = '--check' in sys.argv
stale = [str(p) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
i18n = ROOT / 'mods/tfm2_custom/text/champion.i18n'
loc = json.loads(i18n.read_text(encoding='utf8'))
roster_p = ROOT / 'rules/champions.json'
r = json.loads(roster_p.read_text(encoding='utf8'))
if loc['en']['description'].get(ID) != text:
    stale.append(str(i18n))
if next((c for c in r['champions'] if c['id'] == ID), None) != roster:
    stale.append(str(roster_p))
if check:
    if stale:
        sys.exit('stale: ' + ', '.join(stale))
    print('Thalassa outputs are current')
    sys.exit(0)
for p, s in outputs.items():
    p.write_text(s)
loc['en']['description'][ID] = text
i18n.write_text(json.dumps(loc, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
r['champions'] = [c for c in r['champions'] if c['id'] != ID] + [roster]
roster_p.write_text(json.dumps(r, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
print('Thalassa data, tooltips, editor data and roster entry generated')
