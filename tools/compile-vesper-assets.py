"""Generated read-only tag-to-atlas costs for opt-in profiling."""
from pathlib import Path
from PIL import Image
import json
ROOT=Path(__file__).resolve().parents[1];rows={}
for p in sorted((ROOT/'mods/tfm2_custom/vfx').glob('vesper*#anim.fanim')):
    sheet=p.with_name(p.name.replace('#anim.fanim','#sheet.png'));im=Image.open(sheet);size=im.width*im.height*4
    for tag in json.loads(p.read_text())['anims']:rows[tag]=(p.name.split('#')[0],size)
out=['// Generated by tools/compile-vesper-assets.py.','fn asset_info(tag:&str)->Option<(&\'static str,usize)>{','    match tag {']
for tag,(name,size)in sorted(rows.items()):out.append('        '+json.dumps(tag)+'=>Some(('+json.dumps(name)+','+str(size)+')),')
out+=['        _=>None,','    }','}']
(ROOT/'native/tfm2_custom_ai/src/vesper_assets.rs').write_text('\n'.join(out)+'\n',encoding='utf-8')
print('Profile asset names:',len(rows))
