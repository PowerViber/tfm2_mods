"""Generate Akane's Rust tables, champion data, tooltips, editor data and roster entry from rules/akane.json.

Change numbers in the rules file and rerun; never edit the outputs by hand. `--check` only verifies.
"""
from pathlib import Path
import copy, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'rules/akane.json').read_text())
ID = rules['id']
GROUPS = ['basic', 'orb', 'soul', 'rhythm', 'kunai', 'edge', 'night', 'ai']


def snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).upper()


lines = ['//! Generated by tools/generate-akane.py from rules/akane.json. Do not edit by hand.', '#![allow(dead_code)]', '',
         'pub const RULES_REVISION: &str = ' + json.dumps(rules['revision']) + ';',
         f'pub const MOD_POWER: [i32; 7] = {rules["modPower"]};']
for group in GROUPS:
    for k, v in rules[group].items():
        lines.append(f'pub const {snake(group)}_{snake(k)}: i64 = {v};')
lines.append(f'pub const FX_TOKENS: usize = {rules["fxTokens"]};')
rust = '\n'.join(lines) + '\n'

b, o, so, rh, ku, ed, ni, _ = (rules[k] for k in GROUPS)
sec = lambda n: f'{n / 60:g} s'
text = {
    'name': rules['name'],
    'skill': (f"Soul Harvest (passive): a champion kill or assist leaves a Soul Orb for {sec(o['ticks'])}. After {sec(o['armTicks'])}, staying within "
              f"{o['range']} of it for {sec(o['absorbTicks'])} (she can move) absorbs it: a Soul charge back, Kunai Flip's cooldown reset, and "
              f"Crimson Edge's reset at most once every {sec(o['s3ResetCooldownTicks'])}. "
              f"Blood Rhythm: each basic attack adds a stack (up to {rh['maxStacks']}, {sec(rh['ticks'])}): +{rh['pctPerStack']}% basic-attack damage per stack; at {rh['cleaveStacks']}+ stacks her basic attacks cleave enemies within {rh['cleaveRadius']} of the target ({rh['cleaveMinionPct']}% to minions and creeps, {rh['cleavePct']}% to champions). "
              f"Dismiss & Devour ({so['charges']} charges, {sec(so['rechargeTicks'])} each): for {sec(so['ticks'])} she's invulnerable, {so['speedPct']}% faster "
              f"and invisible until she casts a skill or attacks; she can cast skills, but a second basic attack ends it. She heals "
              f"{so['healPctMaxHp']}% max HP + {so['healAdRatio']}% Attack, and when it ends her damage is {so['ambushPct']}% higher for {sec(so['ambushTicks'])}."),
    'skill2': (f"Kunai Flip ({sec(ku['cooldownTicks'])}): she flips back {ku['flip']} over {sec(ku['flipTicks'])} and throws a non-homing kunai ({ku['range']}, {ku['speed'] * 60} units/s); it pierces up to {ku['pierceMax']} minions and creeps "
               f"(each takes {ku['base']} + {ku['adRatio']}% Attack) and stops at the first champion, who takes it and is marked for {sec(ku['markTicks'])} "
               f"(with no champion, the last minion or creep hit is marked; never a tower). Recast: she dashes to it, over walls too, and "
               f"slashes for {ku['slashBase']} + {ku['slashAdRatio']}% Attack. "
               f"Crimson Edge ({sec(ed['cooldownTicks'])}): her next {ed['hits']} basic attacks within {sec(ed['windowTicks'])}, each also slashing enemies within {ed['splashRadius']} of the target for {ed['splashPct']}%: a bleed "
               f"({ed['bleedBase']} + {ed['bleedAdRatio']}% Attack a second per stack, up to {ed['maxStacks']}); a bleed and {ed['slowPct']}% slow; "
               f"a bleed and {ed['vulnerablePct']}% vulnerable; the 4th stack bursts (on a minion or creep the 4th hit always bursts) for {ed['burstPctMaxHp']}% max HP + {ed['burstAdRatio']}% Attack "
               f"(half around it within {ed['burstRadius']}) with a crimson bleed of {ed['crimsonPermillePerSecond'] / 10:g}% max HP a second; "
               f"the 5th: invulnerable, she teleports behind the target and knocks up enemies within {ed['knockRadius']} for {sec(ed['knockTicks'])}."),
    'ult': (f"Crimson Night ({sec(ni['cooldownTicks'])}): for {sec(ni['ticks'])} every enemy is nearsighted: her team is hidden from them beyond "
            f"{ni['sight']}. Recast once to dash, over walls, to a visible enemy champion within {ni['dashRange']} and slash for {ni['base']} + "
            f"{ni['adRatio']}% Attack; the slash sets off a lesser crimson explosion ({ni['burstPct']}% of Crimson Edge's burst, with the crimson bleed) "
            f"that fears everyone it hits for {sec(ni['fearTicks'])}. Her skills never hit towers."),
}

champ = copy.deepcopy(json.loads((ROOT / 'mods/tfm2_custom/champion/tfm2_custom_contender.data_champion').read_text()))
# her own body sheet (Codex's art); like Wright and Kratos, the game skips her until it exists
champ.update(id=ID, category=rules['category'], tags=rules['tags'], sprite='asset/tfm2_custom/champions/' + ID, anim_prefix='')
for key in ['stat', 'growth']:
    champ[key] = {k: 0 for k in champ[key]}
    champ[key].update(rules[key])
champ['attack'].update(duration=b['duration'], cooltime=b['cooldownTicks'], start_timing=b['startTiming'], range=b['range'],
                       effect={'type': 'Attack', 'damage': 0, 'attack_ratio': 100})
for slot in ['skill', 'skill2', 'ult']:
    champ[slot]['description'] = '#asset/base/text/champion?description.' + ID + '.' + slot
champ['passive'] = {'passive_ref': 'tfm2_custom_ai:akane', 'params': {}}
champ['passive_ult'] = {'passive_ref': 'tfm2_custom_ai:ult_learned', 'params': {}}
VFX = 'asset/tfm2_custom/vfx/akane'
EFFECTS = ['orb', 'orb_absorb', 'dismiss', 'kunai', 'kunai_hit', 'flip', 'dash_slash', 'burst', 'finale', 'knock_up', 'night', 'night_slash']
GROUND = ('orb', 'night')
champ['view_effects'] = [dict(type='Animation', name='akn_' + e, anim=VFX, tag=e, z=-2 if e in GROUND else 6, is_follow=False) for e in EFFECTS]
champ['view_buffs'] = ([dict(type='Animated', name='akn_mark', anim=VFX, tag='mark', z=5),
                        dict(type='Animated', name='akn_crimson', anim=VFX, tag='crimson', z=4),
                        dict(type='Animated', name='akn_vulnerable', anim=VFX, tag='vulnerable', z=4)]
                       + [dict(type='Animated', name=f'akn_bleed:{i}', anim=VFX, tag=f'bleed{i}', z=4) for i in range(1, ed['maxStacks'] + 1)])
art_path = ROOT / 'docs/akane-art-review/art-manifest.json'
if art_path.exists():
    art = json.loads(art_path.read_text())
    if not art['review_only']:
        champ['passive']['params']['art_v1'] = 1
        champ['view_effects'] = [dict(type='Animation', name='akn_' + tag, anim=VFX, tag=tag, z=spec['z'], is_follow=spec.get('follow', False))
                                 for tag, spec in art['effects'].items() if spec['kind'] == 'effect']
        champ['view_buffs'].append(dict(type='Animated', name='akn_night_aura', anim=VFX, tag='night_aura', z=-2))
if not (ROOT / 'mods/tfm2_custom/vfx/akane#sheet.png').exists():
    # no VFX sheet yet: the effects stay native-only (nothing drawn) rather than point at a missing sheet
    champ['view_effects'], champ['view_buffs'] = [], []
addon_path = ROOT / 'docs/round-165-art-review/manifest.json'
if addon_path.exists():
    addon = json.loads(addon_path.read_text(encoding='utf-8'))
    if addon['integrated']:
        for binding in addon['bindings']['akane']:
            spec = dict(type='Animated' if binding['kind']=='buff' else 'Animation', name=binding['name'], anim=addon['asset'], tag=binding['tag'], z=binding['z'])
            if binding['kind']=='effect': spec['is_follow']=False
            champ['view_buffs' if binding['kind']=='buff' else 'view_effects'].append(spec)
        pass

data = json.dumps(champ, indent=2) + '\n'

roster = dict(id=ID, name=rules['name'], family='original', role='Assassin', native=True,
              basicAttack=dict(name='Katana', kind='melee', range=b['range']),
              skills=[dict(slot='skill', name='Soul Harvest / Dismiss & Devour', kinds=['Heal', 'Buff'], intents=['Escape', 'Protect'], summary=text['skill']),
                      dict(slot='skill2', name='Kunai Flip / Crimson Edge', kinds=['Dash', 'Projectile', 'Aoe', 'Cc'], intents=['Engage', 'Escape', 'Clear'],
                           summary=text['skill2']),
                      dict(slot='ult', name='Crimson Night', kinds=['Buff', 'Dash'], intents=['Engage', 'Vision'], summary=text['ult'])])

outputs = {
    ROOT / 'editor/akane-data.js': 'window.AKANE_RULES = ' + json.dumps(rules, separators=(',', ':')) + ';\n',
    ROOT / 'native/tfm2_custom_ai/src/akane_data.rs': rust,
    ROOT / 'mods/tfm2_custom/champion' / f'{ID}.data_champion': data,
}
check = '--check' in sys.argv
stale = [str(p) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
i18n = ROOT / 'mods/tfm2_custom/text/champion.i18n'
loc = json.loads(i18n.read_text(encoding='utf8'))
roster_p = ROOT / 'rules/champions.json'
r = json.loads(roster_p.read_text(encoding='utf8'))
if loc['en']['description'].get(ID) != text:
    stale.append(str(i18n))
if next((c for c in r['champions'] if c['id'] == ID), None) != roster:
    stale.append(str(roster_p))
if check:
    if stale:
        sys.exit('stale: ' + ', '.join(stale))
    print('Akane outputs are current')
    sys.exit(0)
for p_, s in outputs.items():
    p_.write_text(s)
loc['en']['description'][ID] = text
i18n.write_text(json.dumps(loc, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
r['champions'] = [c for c in r['champions'] if c['id'] != ID] + [roster]
roster_p.write_text(json.dumps(r, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
print('Akane data, tooltips, editor data and roster entry generated')
