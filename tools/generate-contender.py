"""Generate Contender's Rust tables, champion data, tooltips, editor data and roster entry from rules/contender.json.

Contender 2.5, the elusive Shadow Boxer (round 178). Change numbers in the rules file and rerun; never edit the outputs by hand.
`--check` only verifies.
"""
from pathlib import Path
import copy, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'rules/contender.json').read_text())
ID = rules['id']
GROUPS = ['basic', 'charges', 'pact', 'rhythm', 'merge', 'cyclone', 'tether', 'ult', 'ai']


def snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).upper()


lines = ['//! Generated by tools/generate-contender.py from rules/contender.json. Do not edit by hand.', '#![allow(dead_code)]', '',
         'pub const RULES_REVISION: &str = ' + json.dumps(rules['revision']) + ';',
         f'pub const MOD_POWER: [i32; 7] = {rules["modPower"]};']
for group in GROUPS:
    for k, v in rules[group].items():
        lines.append(f'pub const {snake(group)}_{snake(k)}: i64 = {v};')
lines.append(f'pub const FX_TOKENS: usize = {rules["fxTokens"]};')
rust = '\n'.join(lines) + '\n'

b, ch, pa, rh, me, cy, te, ul, _ = (rules[k] for k in GROUPS)
sec = lambda n: f'{n / 60:g} s'
text = {
    'name': rules['name'],
    'skill': (f"Shadows (passive): up to {ch['max']} shadow dodges, one every {sec(ch['rechargeTicks'])} (each basic attack that lands takes "
              f"{sec(ch['basicCutTicks'])} off). When an enemy champion's attack or skill hits him, a dodge is spent: he slips {ch['dodgeSlip']} "
              f"aside and the hit is undone (at most one dodge every {sec(ch['dodgeGapTicks'])}). His skills never cost dodges; each can be recast "
              f"once, free, within {sec(ch['recastWindowTicks'])}. "
              f"Shadow Pact (passive): every punch and skill hits again {sec(pa['delayTicks'])} later for {pa['pct']}%, with its crowd control at "
              f"{pa['ccPct']}% (at most {sec(pa['ccCapTicks'])} more per target every {sec(pa['ccWindowTicks'])}); recast hits echo twice. Echoes never add Rhythm stacks. "
              f"Shadow Rhythm (passive): each hit of his (not an echo) stacks on its target (up to {rh['maxStacks']}, {sec(rh['stackTicks'])}); the most-stacked enemy "
              f"gives him +{rh['attackSpeedPermillePerStack'] / 10:g}% attack speed"
              + (f", +{rh['attackPermillePerStack'] / 10:g}% Attack" if rh['attackPermillePerStack'] else '') + f" and "
              f"+{rh['moveSpeedPermillePerStack'] / 10:g}% move speed per stack, and takes +{rh['vulnerabilityPermillePerStack'] / 10:g}% damage "
              f"from him per stack. At {rh['maxStacks']} stacks his next hit is a Shadow Break: {rh['breakPermilleMaxHp'] / 10:g}% of its max HP + "
              f"{rh['breakAdRatio']}% Attack, and its stacks reset to 0, but his Rhythm buffs stay at full for {sec(rh['breakBuffTicks'])}. A max-stacked creep carries {rh['carryStacks']} stacks "
              f"onto the next champion he hits; a stacked kill keeps the buffs {sec(rh['lingerTicks'])} longer. "
              f"S1 Shadow Merge ({sec(me['cooldownTicks'])}): he merges with his shadow for {sec(me['ticks'])}: dodges recharge {me['rechargeMult']}x "
              f"as fast, +{me['bonusDodges']} dodges at once, every hit echoes twice and adds {me['stacksPerHit']} stacks, +{me['moveSpeedPct']}% "
              f"move speed. Recast: he steps out; the shadow's cross knocks the nearest enemy {me['crossKnock']} back ({me['crossBase']} + "
              f"{me['crossAdRatio']}% Attack) and he slips {me['slip']} away."),
    'skill2': (f"Shadow Cyclone ({sec(cy['cooldownTicks'])}): a shadow clone goes to a spot within {cy['range']} and cleaves the circle around "
               f"it ({cy['radius']}): {cy['hits']} hits of {cy['base']} + {cy['adRatio']}% Attack and a {cy['slowPct']}% slow; it can't be hit. "
               f"Recast: he cleaves himself anywhere within {cy['recastRange']}, invulnerable, in a {cy['recastRadius']} circle: {cy['recastHits']} hits "
               f"of {cy['recastBase']} + {cy['recastAdRatio']}% Attack, each pulling enemies {cy['recastPull']} toward the centre, the last knocking "
               f"up for {sec(cy['recastKnockTicks'])}. "
               f"Shadow Tether ({sec(te['cooldownTicks'])}): a shadow latches onto every enemy within {te['radius']} (up to {te['max']}) for "
               f"{sec(te['ticks'])}; each hit he lands is copied onto every tethered enemy at {te['copyPct']}% (flurry punches at "
               f"{te['flurryCopyPct']}%), with a stack each. A tether breaks past {te['breakRange']}. Recast: every tethered enemy is yanked "
               f"{te['yank']} toward him and uppercut ({te['base']} + {te['adRatio']}% Attack, {sec(te['knockTicks'])} airborne)."),
    'ult': (f"Shadow Flurry (no cooldown): every hit of his outside the flurry banks a shadow stack (up to {ul['bankMax']}); with "
            f"{ul['bankMax']} banked he can cast it, spending them all. He melts into the ground, untargetable and unhurt for {sec(ul['ticks'])}, "
            f"and his dodges refill. His shadows strike the enemy nearest him (within {ul['startRange']}), then chain {ul['punches']} punches, "
            f"slow at first and faster at the end, each onto an enemy within {ul['chainRange']} of the last one hit ({ul['base']} + "
            f"{ul['adRatio']}% Attack). Each punch prefers a different eligible enemy; it repeats the last target only when no alternative is in reach. "
            f"Cast while merged, every punch echoes. Every second the last enemy hit is knocked up. With nothing left in reach the flurry ends early. He "
            f"reappears beside the last enemy hit, and his next basic within {sec(ul['haymakerTicks'])} is a haymaker "
            f"(+{ul['haymakerBase']} + {ul['haymakerAdRatio']}% Attack, a {sec(ul['haymakerStunTicks'])} stun). His skills never hit towers."),
}
text['skill'] += ' Level unlocks: S2 at level 2, S3 at level 3, the ult at level 5.'  # round 180 (tools: unlocks.rs)

champ = copy.deepcopy(json.loads((ROOT / 'tools/native-champion-template.json').read_text()))
champ.update(id=ID, category=rules['category'], tags=rules['tags'], sprite='asset/tfm2_custom/champions/' + ID, anim_prefix='')
for key in ['stat', 'growth']:
    champ[key] = {k: 0 for k in champ[key]}
    champ[key].update(rules[key])
champ['attack'].update(duration=b['duration'], cooltime=b['cooldownTicks'], start_timing=b['startTiming'], range=b['range'],
                       effect={'type': 'Attack', 'damage': 0, 'attack_ratio': 100})
for slot in ['skill', 'skill2', 'ult']:
    champ[slot]['description'] = '#asset/base/text/champion?description.' + ID + '.' + slot
champ['passive'] = {'passive_ref': 'tfm2_custom_ai:contender', 'params': {'shadow_art_v1': 1, 'shadow_directions_v1': 1, 'shadow_merge_art_v1': 1, 'shadow_rhythm_art_v1': 1}}
champ['passive_ult'] = {'passive_ref': 'tfm2_custom_ai:ult_learned', 'params': {}}
# his shadow effects arrive with Codex's art (`docs/contender-shadow-art-handoff.md`); until then every name he plays is
# bound to existing effects so the shadow, its cleaves, slams and the flurry are visible in a playtest
PLACEHOLDER = {'shadow': ('kagami', 'clone_in'), 'launch': ('kicker', 'dash'), 'swap': ('kagami', 'swap'), 'cross': ('kicker', 'kick'),
               'cleave': ('grimhald', 'slash'), 'slam': ('grimhald', 'slam'), 'uppercut': ('kicker', 'drop_in'),
               'echo': ('kagami', 'shard_hit'), 'vanish': ('grimhald', 'ghost'), 'appear': ('grimhald', 'ghost_end'),
               'flurry': ('akane', 'dash_slash'), 'haymaker': ('kicker', 'wall_slam')}
champ['view_effects'] = [dict(type='Animation', name='ct_' + e, anim='asset/tfm2_custom/vfx/' + sheet, tag=tag, z=-2 if e == 'vanish' else 5,
                              is_follow=False) for e, (sheet, tag) in PLACEHOLDER.items()]
champ['view_buffs'] = []
champ['view_projectiles'] = []
art = json.loads((ROOT/'docs/contender-shadow-review/presentation.json').read_text())
champ['view_effects'] = [dict(type='Animation', name=e['name'], anim='asset/tfm2_custom/vfx/contender_shadow',
                            tag=e['tag'], z=e['z'], is_follow=e['follow']) for e in art['bindings']]
champ['view_buffs'] = [dict(type='Animated', name=f'ct_charges:{i}', anim='asset/tfm2_custom/vfx/contender_shadow',
                          tag=f'charges{i}', z=6) for i in range(6)]
champ['view_buffs'] += [dict(type='Animated', name=e['name'], anim='asset/tfm2_custom/champions/tfm2_custom_contender_merge',
                           tag=e['tag'], z=e['z']) for e in art['merge_bindings']]
champ['view_effects'] += [dict(type='Animation', name=e['name'], anim='asset/tfm2_custom/vfx/contender_rhythm',
                             tag=e['tag'], z=e['z'], is_follow=e['follow']) for e in art['rhythm_bindings']]
champ['view_buffs'] += [dict(type='Animated', name=e['name'], anim='asset/tfm2_custom/vfx/contender_rhythm',
                           tag=e['tag'], z=e['z']) for e in art['rhythm_buffs']]

data = json.dumps(champ, indent=2) + '\n'

roster = dict(id=ID, name=rules['name'], family='original', role='Fighter', native=True,
              basicAttack=dict(name='Jab / Cross', kind='melee', range=b['range']),
              skills=[dict(slot='skill', name='Shadows / Shadow Pact / Shadow Rhythm / Shadow Merge', kinds=['Dash', 'Buff'],
                           intents=['Engage', 'Escape'], summary=text['skill']),
                      dict(slot='skill2', name='Shadow Cyclone / Shadow Tether', kinds=['Aoe', 'Cc'],
                           intents=['Engage', 'Clear'], summary=text['skill2']),
                      dict(slot='ult', name='Shadow Flurry', kinds=['Aoe', 'Cc'], intents=['Engage'], summary=text['ult'])])

outputs = {
    ROOT / 'editor/contender-data.js': 'window.CONTENDER_RULES = ' + json.dumps(rules, separators=(',', ':')) + ';\n',
    ROOT / 'native/tfm2_custom_ai/src/contender_shadow_data.rs': rust,
    ROOT / 'mods/tfm2_custom/champion' / f'{ID}.data_champion': data,
}
check = '--check' in sys.argv
stale = [str(p) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
i18n = ROOT / 'mods/tfm2_custom/text/champion.i18n'
loc = json.loads(i18n.read_text(encoding='utf8'))
roster_p = ROOT / 'rules/champions.json'
r = json.loads(roster_p.read_text(encoding='utf8'))
if loc['en']['description'].get(ID) != text:
    stale.append(str(i18n))
if next((c for c in r['champions'] if c['id'] == ID), None) != roster:
    stale.append(str(roster_p))
if check:
    if stale:
        sys.exit('stale: ' + ', '.join(stale))
    print('Contender outputs are current')
    sys.exit(0)
for p_, s in outputs.items():
    p_.write_text(s)
loc['en']['description'][ID] = text
i18n.write_text(json.dumps(loc, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
existing = [c['id'] for c in r['champions']]
if ID in existing:
    r['champions'] = [roster if c['id'] == ID else c for c in r['champions']]
else:
    r['champions'].append(roster)
roster_p.write_text(json.dumps(r, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
print('Contender data, tooltips, editor data and roster entry generated')
