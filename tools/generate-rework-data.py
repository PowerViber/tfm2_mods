"""Generate Frieren's native/editor constants from the canonical rework catalogue."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'Claude outputs/unified_theory/rework.json').read_text())
lines=['// Generated by tools/generate-rework-data.py; edit the canonical rework.json.']
for key,value in data['constants'].items():
 kind='usize' if key.endswith('_TICKS') else 'i64'
 lines.append(f'pub const {key}: {kind} = {value};')
(ROOT/'native/tfm2_custom_ai/src/rework_data.rs').write_text('\n'.join(lines)+'\n')
(ROOT/'editor/rework-data.js').write_text('/* Generated from the canonical rework.json. */\n(function(r){const d='+json.dumps(data,separators=(',',':'))+";if(typeof module!=='undefined')module.exports=d;else r.ReworkData=d;})(globalThis);\n")
print('Generated',len(data['constants']),'Frieren combat constants')
