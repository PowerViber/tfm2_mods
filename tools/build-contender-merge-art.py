"""Pack the approved Merge animation extension; leave normal bodies/FX untouched."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'docs/contender-merge-review'
approval = json.loads((OUT/'approvals.json').read_text())['appearance']
assert approval['approved']
assert hashlib.sha256((OUT/'merge-source-v1.png').read_bytes()).hexdigest() == approval['source_sha256']
source = OUT/'merge-animation-source-v1.png'
im = Image.open(source).convert('RGBA')
assert im.size == (1536, 1024)
N = Image.Resampling.NEAREST
tiles = []
for row in range(4):
    for col in range(6):
        cell = im.crop((col*256, row*256, (col+1)*256, (row+1)*256))
        cell.putalpha(cell.getchannel('A').point(lambda a: 255 if a >= 180 else 0))
        cell = cell.quantize(colors=32, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).convert('RGBA').resize((48,48),N)
        tile = Image.new('RGBA',(80,64))
        ax = [126,127,128,127,127,127][col]
        tile.alpha_composite(cell,(40-round(ax*3/16),52-round(242*3/16)))
        tiles.append(tile)

manifest_path = ROOT/'docs/contender-shadow-review/presentation.json'
manifest = json.loads(manifest_path.read_text())
body = manifest['body']['anims']
# Reuse the normal atlas's tile identity, aliases, frame counts and durations.
sheet = Image.new('RGBA',(960,256))
rects = {}
for i,tile in enumerate(tiles):
    for left in [False,True]:
        at=i*2+int(left);x=at%12*80;y=at//12*64
        frame=tile
        if left:
            frame=Image.new('RGBA',tile.size)
            frame.alpha_composite(ImageOps.mirror(tile),(1,0))
        sheet.alpha_composite(frame,(x,y))
        rects[(i,left)]=dict(x=x,y=y,w=80,h=64)

anims = json.loads(json.dumps(body))
clock = {}
for name,a in anims.items():
    if not name.endswith('_l'):
        clock[name] = [dict(tile=(f['data']['y']//64*12+f['data']['x']//80)//2,
                            milli_ticks=round(f['duration']*60000)) for f in a['frames']]
for i in range(24):
    for left in [False,True]:
        anims[f'tile{i}'+('_l' if left else '')] = {'frames':[{'duration':6,'data':rects[(i,left)]}]}
stem=ROOT/'mods/tfm2_custom/champions/tfm2_custom_contender_merge'
sheet.save(str(stem)+'#sheet.png')
Path(str(stem)+'#anim.fanim').write_text(json.dumps({'anims':anims},separators=(',',':'))+'\n')
manifest['merge'] = dict(file='../mods/tfm2_custom/champions/tfm2_custom_contender_merge#sheet.png',anims=anims,
                         clock=clock, buff_prefix='ct_mb_', frame_duration_ticks=360)
manifest['merge_bindings'] = [dict(name=f'ct_mb_{i}'+('_l' if left else ''),tag=f'tile{i}'+('_l' if left else ''),z=4)
                               for i in range(24) for left in [False,True]]
manifest['merge_source_hashes'] = {p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in [OUT/'merge-source-v1.png',source]}
manifest['revision']='contender-shadow-art-3'
manifest['rules']=json.loads((ROOT/'rules/contender.json').read_text())['revision']
manifest['decoded_bytes']=sum(Image.open(ROOT/manifest[k]['file'].removeprefix('../')).width*
                               Image.open(ROOT/manifest[k]['file'].removeprefix('../')).height*4 for k in ['body','effects','merge'])
assert manifest['decoded_bytes'] <= 32*1024*1024
manifest_path.write_text(json.dumps(manifest,indent=2)+'\n')
(ROOT/'editor/contender-presentation.js').write_text('window.CONTENDER_PRESENTATION='+json.dumps(manifest,separators=(',',':'))+';\n')
rust='// Generated by tools/build-contender-merge-art.py. Presentation only.\n'
rust+='pub fn sequence(pose: &str) -> &\'static [(usize, u64)] {\n    match pose {\n'
for pose,frames in clock.items():
    rust+=f'        "{pose}" => &['+','.join(f'({f["tile"]},{f["milli_ticks"]})' for f in frames)+'],\n'
rust+='        _ => &[(0, 12000)],\n    }\n}\n'
(ROOT/'native/tfm2_custom_ai/src/contender_merge_data.rs').write_text(rust)
(OUT/'presentation.json').write_text(json.dumps(dict(approved=True,source_hashes=manifest['merge_source_hashes'],
                         atlas=[960,256],decoded_total_bytes=manifest['decoded_bytes'],clock=clock,
                         generation_deterministic=False,packing_deterministic=True),indent=2)+'\n')
print(json.dumps(dict(atlas=[960,256],decoded_total_bytes=manifest['decoded_bytes'],poses=len(clock),source_hash=manifest['merge_source_hashes'][source.name])))
