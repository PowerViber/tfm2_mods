"""Generate Wright's Rust tables, champion data, tooltips, editor data and roster entry from rules/wright.json.

Change numbers in the rules file and rerun; never edit the outputs by hand. `--check` only verifies.
"""
from pathlib import Path
import copy, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'rules/wright.json').read_text())
ID = rules['id']
GROUPS = ['basic', 'workshop', 'fighter', 'bomber', 'repair', 'carrier', 'drone']


def snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).upper()


lines = ['//! Generated by tools/generate-wright.py from rules/wright.json. Do not edit by hand.', '#![allow(dead_code)]', '',
         'pub const RULES_REVISION: &str = ' + json.dumps(rules['revision']) + ';',
         f'pub const MOD_POWER: [i32; 7] = {rules["modPower"]};']
for group in GROUPS:
    for k, v in rules[group].items():
        lines.append(f'pub const {snake(group)}_{snake(k)}: i64 = {v};')
lines.append(f'pub const FX_TOKENS: usize = {rules["fxTokens"]};')
rust = '\n'.join(lines) + '\n'

b, w, fi, bo, re_, ca, dr = (rules[k] for k in GROUPS)
sec = lambda n: f'{n / 60:g} s'
text = {
    'name': rules['name'],
    'skill': (f"Workshop (passive): builds an airframe every {sec(w['buildTicks'])} (up to {w['maxStock']}); each skill uses one. Every {sec(w['droneEveryTicks'])} "
              f"a scout drone ({dr['hpPct']}% of his HP) flies to the nearest enemy champion, hovers {sec(dr['hoverTicks'])} and taunts enemies within "
              f"{dr['tauntRadius']} onto it for {sec(dr['tauntTicks'])}. "
              f"Fighter Wing ({sec(fi['cooldownTicks'])}): launches {fi['perCast']} fighters for {sec(fi['ticks'])} (up to {fi['maxAlive']}, {fi['hpPct']}% of his HP "
              f"each, can be shot down). They circle him and dogfight: they boost in on attack runs with a machine gun ({fi['gunBase']} + {fi['gunApRatio']}% AP every "
              f"{sec(fi['gunEveryTicks'])}) and a lock-on rocket every {sec(fi['rocketEveryTicks'])} ({fi['rocketBase']} + {fi['rocketApRatio']}% AP), break away and "
              f"come around again; with no champion near they clear minions and camps. They never damage turrets. When their time ends or they fall below "
              f"{fi['kamikazeHpPct']}% HP they kamikaze: {fi['kamikazeBase']} + {fi['kamikazeApRatio']}% AP, a knockback and a burn of "
              f"{fi['burnPermillePerSecond'] / 10:g}% max HP a second for {sec(fi['burnTicks'])}."),
    'skill2': (f"Carpet Bomber ({sec(bo['cooldownTicks'])}): marks an area and, after {sec(bo['warnTicks'])}, a bomber drops {bo['waves']} carpet waves "
               f"({bo['waveBase']} + {bo['waveApRatio']}% AP each): the first ones slow {bo['slowPct']}%, the last stuns {sec(bo['stunTicks'])}. "
               f"Repair Wing ({sec(re_['cooldownTicks'])}): a repair chopper circles him and a repair plane flies to the most hurt ally anywhere, both for "
               f"{sec(re_['ticks'])}. Every {sec(re_['kitEveryTicks'])} each drops a kit: {re_['healPermille'] / 10:g}% max HP and a {re_['shieldBase']} + "
               f"{re_['shieldApRatio']}% AP shield (up to {re_['shieldCapBase']} + {re_['shieldCapApRatio']}% AP). The chopper also repairs his fighters."),
    'ult': (f"Sky Carrier ({sec(ca['cooldownTicks'])}): a carrier drops from the sky on Wright, knocking enemies away (the closer, the farther, up to "
            f"{ca['knockMax']}) and slowing them {ca['slowPct']}%, with no damage. It hovers over him for {sec(ca['ticks'])} and takes {ca['guardPct']}% of the damage "
            f"he takes (until its pool of {ca['poolPct']}% of his HP runs out). It launches a fighter every {sec(ca['fighterEveryTicks'])} (up to {ca['maxFighters']}) "
            f"and a repair chopper every {sec(ca['chopperEveryTicks'])}, and readies a bomber every {sec(ca['bomberEveryTicks'])} (up to {ca['maxReadyBombers']}): "
            f"while it's up, Carpet Bomber uses a ready bomber, with no airframe or cooldown."),
}

champ = copy.deepcopy(json.loads((ROOT / 'mods/tfm2_custom/champion/tfm2_custom_contender.data_champion').read_text()))
champ.update(id=ID, category=rules['category'], tags=rules['tags'], sprite='asset/tfm2_custom/champions/' + ID, anim_prefix='')
for key in ['stat', 'growth']:
    champ[key] = {k: 0 for k in champ[key]}
    champ[key].update(rules[key])
champ['attack'].update(duration=22, cooltime=b['cooldownTicks'], start_timing=12, range=b['range'],
                       effect={'type': 'TargetProjectile', 'speed': b['boltSpeed'], 'name': ID + '_rivet', 'y_offset': 0, 'applied_target': 'Enemy',
                               'applied_effects': [{'effect': {'type': 'ApAttack', 'damage': b['base'], 'attack_ratio': b['apRatio']}, 'casting_type': 'Targeting'}]})
for slot in ['skill', 'skill2', 'ult']:
    champ[slot]['description'] = '#asset/base/text/champion?description.' + ID + '.' + slot
champ['passive'] = {'passive_ref': 'tfm2_custom_ai:wright', 'params': {}}
champ['passive_ult'] = {'passive_ref': 'tfm2_custom_ai:ult_learned', 'params': {}}
VFX = 'asset/tfm2_custom/vfx/wright'
HEADED = ['fighter', 'bomber', 'chopper', 'repair', 'drone', 'rocket']
EFFECTS = (['carrier', 'carrier_shadow', 'carrier_land', 'mg', 'lock', 'kamikaze', 'bomb', 'warn', 'repair_kit', 'knock_ring', 'drone_up', 'taunt']
           + [f'{h}_p{i}' for h in HEADED for i in range(8)])
GROUND = ('carrier_shadow', 'warn', 'knock_ring')
champ['view_effects'] = [dict(type='Animation', name='wrt_' + e, anim=VFX, tag=e, z=-2 if e in GROUND else 6, is_follow=False) for e in EFFECTS]
champ['view_buffs'] = [dict(type='Animated', name='wrt_burn', anim=VFX, tag='burn', z=4),
                       dict(type='Animated', name='wrt_shielded', anim=VFX, tag='repair_shield', z=4)]
champ['view_projectiles'] = [dict(type='Animated', name=ID + '_rivet', anim=VFX, tag='rivet', z=2, repeat=True)]
data = json.dumps(champ, indent=2) + '\n'

roster = dict(id=ID, name=rules['name'], family='original', role='Magician', native=True,
              basicAttack=dict(name='Rivet gun', kind='ranged', range=b['range']),
              skills=[dict(slot='skill', name='Workshop / Fighter Wing', kinds=['Summon', 'Projectile', 'Cc'], intents=['Poke', 'Clear', 'Vision'], summary=text['skill']),
                      dict(slot='skill2', name='Carpet Bomber / Repair Wing', kinds=['Aoe', 'Zone', 'Heal', 'Shield'], intents=['Engage', 'Protect', 'Clear'],
                           summary=text['skill2']),
                      dict(slot='ult', name='Sky Carrier', kinds=['Summon', 'Aoe', 'Cc'], intents=['Engage', 'Objective'], summary=text['ult'])])

outputs = {
    ROOT / 'editor/wright-data.js': 'window.WRIGHT_RULES = ' + json.dumps(rules, separators=(',', ':')) + ';\n',
    ROOT / 'native/tfm2_custom_ai/src/wright_data.rs': rust,
    ROOT / 'mods/tfm2_custom/champion' / f'{ID}.data_champion': data,
}
check = '--check' in sys.argv
stale = [str(p) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
i18n = ROOT / 'mods/tfm2_custom/text/champion.i18n'
loc = json.loads(i18n.read_text(encoding='utf8'))
roster_p = ROOT / 'rules/champions.json'
r = json.loads(roster_p.read_text(encoding='utf8'))
if loc['en']['description'].get(ID) != text:
    stale.append(str(i18n))
if next((c for c in r['champions'] if c['id'] == ID), None) != roster:
    stale.append(str(roster_p))
if check:
    if stale:
        sys.exit('stale: ' + ', '.join(stale))
    print('Wright outputs are current')
    sys.exit(0)
for p, s in outputs.items():
    p.write_text(s)
loc['en']['description'][ID] = text
i18n.write_text(json.dumps(loc, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
r['champions'] = [c for c in r['champions'] if c['id'] != ID] + [roster]
roster_p.write_text(json.dumps(r, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
print('Wright data, tooltips, editor data and roster entry generated')
