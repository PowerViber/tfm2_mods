"""Generate the Unified Theory equation kit from its canonical catalogue.

Claude outputs/unified_theory/equations.json -> native data (unified_eq_data.rs), editor data
(editor/unified-equations.js) and the complete combo list (docs/unified-combos.md): every
two-step combo (18 x 18 = 324) and the 36 named signatures. `--check` fails if any output
would change.
"""
from pathlib import Path
import json, sys

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'Claude outputs/unified_theory/equations.json'
SCIENCE = ['Einstein', 'Newton', 'Curie']
FX = ['critical', 'rain', 'focus', 'gamma', 'extend', 'lineknock', 'spectrum', 'repeat', 'markjump',
      'wallless', 'slowcap', 'detonate', 'pulse', 'derivative', 'burst', 'reveal']
SHAPES = ['lob', 'line', 'planet', 'cradle', 'self', 'bolt', 'zone', 'ally']
RUST_SHAPE = {'self': 'Caster'}
KINDS = ['phys', 'magic', 'true']


def load():
    d = json.loads(SRC.read_text(encoding='utf-8'))
    keys = [s['key'] for s in d['skills']]
    assert len(keys) == 18 and len(set(keys)) == 18, 'eighteen distinct skills'
    assert [sum(s['science'] == k for s in d['skills']) for k in range(3)] == [6, 6, 6], 'six per scientist'
    assert [t['skill'] for t in d['traits']] == keys, 'one trait per skill, in skill order'
    assert len(d['signatures']) == 36, 'thirty-six signatures'
    seen = set()
    for g in d['signatures']:
        steps = tuple(g['steps'])
        assert 3 <= len(steps) <= 5 and steps not in seen, steps
        assert all(k in keys or (k == 'ult' and i == len(steps) - 1) for i, k in enumerate(steps)), steps
        assert all(f[0] in FX for f in g['fx']), g['fx']
        seen.add(steps)
    names = [s['name'] for s in d['skills']] + [g['name'] for g in d['signatures']] + [u['name'] for u in d['unification']]
    assert len(names) == len(set(names)), 'unique names'
    orders = sorted(tuple(u['order']) for u in d['unification'])
    assert orders == sorted({(a, b, c) for a in range(3) for b in range(3) for c in range(3) if len({a, b, c}) == 3}), 'six orders'
    for s in d['skills']:
        assert s['shape'] in SHAPES and s['kind'] in KINDS and s['cd'] in d['cooldowns'], s['key']
    return d, keys


def rust(d, keys):
    c = d['constants']
    out = ['// Generated by tools/generate-unified-equations.py from Claude outputs/unified_theory/equations.json. Do not edit.',
           '#![allow(dead_code)]']
    for k, v in c.items():
        kind = 'usize' if k.endswith('_TICKS') or k in ('CHARGES', 'MAX_RESERVE') else 'i64'
        out.append(f'pub const {k}: {kind} = {v};')
    out.append('#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Shape { ' + ', '.join(RUST_SHAPE.get(s, s.capitalize()) for s in SHAPES) + ' }')
    out.append('#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Kind { Phys, Magic, True }')
    out.append('#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Fx { ' + ', '.join(f.capitalize() for f in FX) + ' }')
    out.append('#[derive(Debug)]\npub struct Equation { pub key: &\'static str, pub name: &\'static str, pub science: usize, pub equation: &\'static str, '
               'pub shape: Shape, pub kind: Kind, pub base: i64, pub ad: i64, pub ap: i64, pub hp: i64, pub range: i64, pub speed: i64, '
               'pub width: i64, pub radius: i64, pub life: usize, pub period: usize, pub flight: usize, pub stop: bool, pub pierce: usize, '
               'pub walls: bool, pub turn: i64, pub jumps: usize, pub jump: i64, pub cooldown: usize, pub trait_name: &\'static str, pub adjective: &\'static str }')
    out.append('pub static EQS: [Equation; 18] = [')
    for s, t in zip(d['skills'], d['traits']):
        g = lambda k, v=0: s.get(k, v)
        out.append(f'    Equation {{ key: {json.dumps(s["key"])}, name: {json.dumps(s["name"], ensure_ascii=False)}, science: {s["science"]}, '
                   f'equation: {json.dumps(s["equation"], ensure_ascii=False)}, shape: Shape::{RUST_SHAPE.get(s["shape"], s["shape"].capitalize())}, '
                   f'kind: Kind::{s["kind"].capitalize()}, base: {g("base")}, ad: {g("ad")}, ap: {g("ap")}, hp: {g("hp")}, range: {g("range")}, '
                   f'speed: {g("speed")}, width: {g("width")}, radius: {g("radius")}, life: {g("life")}, period: {g("period")}, flight: {g("flight")}, '
                   f'stop: {str(g("stop", False)).lower()}, pierce: {g("pierce")}, walls: {str(g("walls", False)).lower()}, turn: {g("turn")}, '
                   f'jumps: {g("jumps")}, jump: {g("jump")}, cooldown: {d["cooldowns"][s["cd"]]}, trait_name: {json.dumps(t["name"])}, '
                   f'adjective: {json.dumps(t["adjective"])} }},')
    out.append('];')
    out.append('/// Skill index used for "the ultimate" as the last step of a signature.\npub const ULT_STEP: u8 = 255;')
    out.append('pub struct Signature { pub steps: &\'static [u8], pub name: &\'static str, pub bonus: i64, pub fx: &\'static [(Fx, i64)] }')
    out.append('pub static SIGNATURES: [Signature; 36] = [')
    for g in d['signatures']:
        steps = ', '.join('ULT_STEP' if k == 'ult' else str(keys.index(k)) for k in g['steps'])
        fx = ', '.join(f'(Fx::{f.capitalize()}, {v})' for f, v in g['fx'])
        out.append(f'    Signature {{ steps: &[{steps}], name: {json.dumps(g["name"], ensure_ascii=False)}, bonus: {g["bonus"]}, fx: &[{fx}] }},')
    out.append('];')
    out.append('pub static UNIFICATION: [([usize; 3], &str); 6] = [')
    for u in d['unification']:
        out.append(f'    ({u["order"]}, {json.dumps(u["name"])}),')
    out.append('];')
    return '\n'.join(out) + '\n'


def js(d):
    return ('/* Generated by tools/generate-unified-equations.py from equations.json. */\n'
            "(function(r){const d=" + json.dumps(d, ensure_ascii=False, separators=(',', ':')) +
            ";if(typeof module!=='undefined')module.exports=d;else r.UnifiedEquations=d;})(globalThis);\n")


def pair_text(d, a, b):
    """Two-step combo: `a` reserved as a trait, `b` cast."""
    s, t = d['skills'][b], d['traits'][a]
    zone = s['shape'] == 'zone'
    name = (f'Doubly {t["adjective"]}' if a == b else t['adjective']) + ' ' + s['name']
    trait = t['zone' if zone else 'hit']
    if a == b:
        trait = 'doubled: ' + trait
    eq = f'{d["skills"][a]["equation"]} ▸ {s["equation"]}'
    return name, eq, f'{s["name"]}, and {trait}.'


def markdown(d, keys):
    sk = d['skills']
    lines = ['# Unified Theory: every combo', '',
             'Generated by `tools/generate-unified-equations.py` from `Claude outputs/unified_theory/equations.json`.', '',
             'Unified has **5 charges**, each refilling on its own 6 s timer. Every skill can be **cast** or **reserved**. '
             'A reserved skill spends a charge and becomes a **trait**; the next cast skill gets every reserved trait, '
             'in the order reserved. Up to 4 reserved + 1 cast = a 5-step combo. Order matters (`Prism ▸ Well` ≠ `Well ▸ Prism`). '
             'Reserving the same skill twice doubles its trait (capped at × 2). Each link adds +25%; a step taken within 0.4 s of the '
             'previous one is an **Insight** (+15%). A combo that uses all three scientists also fires a **Unification**, '
             'chosen by the order in which the scientists first appear.', '',
             '## The 18 skills', '', '| # | Skill | Scientist | Equation | Cast | Cooldown |', '|---|---|---|---|---|---|']
    for i, s in enumerate(sk):
        lines.append(f'| {i + 1} | **{s["name"]}** | {SCIENCE[s["science"]]} | `{s["equation"]}` | {s["text"]} | {d["cooldowns"][s["cd"]] / 60:g} s |')
    lines += ['', '## The 18 traits (what a skill gives when reserved)', '', '| Reserved | Trait | On a hit skill | On a zone |', '|---|---|---|---|']
    for s, t in zip(sk, d['traits']):
        lines.append(f'| {s["name"]} | **{t["name"]}** ({t["adjective"]}) | {t["hit"]} | {t["zone"]} |')
    lines += ['', '## Unification (all three scientists in one combo)', '', '| First-appearance order | Name | Payoff |', '|---|---|---|']
    for u in d['unification']:
        lines.append(f'| {" → ".join(SCIENCE[k] for k in u["order"])} | **{u["name"]}** | {u["text"]} |')
    lines += ['', '## Signature combos (36)', '', 'A signature fires when the reserved steps and the cast match exactly. '
              'It adds its bonus on top of the traits and its own effect.', '',
              '| # | Steps (▸ = reserved, last = cast) | Name | Bonus | Effect |', '|---|---|---|---|---|']
    for i, g in enumerate(d['signatures']):
        steps = ' ▸ '.join('**Ultimate**' if k == 'ult' else sk[keys.index(k)]['name'] for k in g['steps'])
        lines.append(f'| {i + 1} | {steps} | **{g["name"]}** | +{g["bonus"]}% | {g["text"]} |')
    lines += ['', '## Every two-step combo (18 × 18 = 324)', '',
              'Rows are grouped by the cast skill. Longer combos (3–5 steps) apply each reserved trait in turn by the same rules.', '']
    n = 0
    for b, s in enumerate(sk):
        lines += [f'### Cast: {s["name"]} (`{s["equation"]}`)', '', '| Reserved ▸ cast | Name | Equations | Effect |', '|---|---|---|---|']
        for a in range(18):
            name, eq, text = pair_text(d, a, b)
            lines.append(f'| {sk[a]["name"]} ▸ {s["name"]} | **{name}** | `{eq}` | {text} |')
            n += 1
        lines.append('')
    assert n == 324
    return '\n'.join(lines) + '\n'


def main():
    d, keys = load()
    outputs = {
        ROOT / 'native/tfm2_custom_ai/src/unified_eq_data.rs': rust(d, keys),
        ROOT / 'editor/unified-equations.js': js(d),
        ROOT / 'docs/unified-combos.md': markdown(d, keys),
    }
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding='utf-8') != text]
    if '--check' in sys.argv:
        assert not stale, f'stale generated files: {stale}'
        print('unified equations: up to date')
        return
    for p in stale:
        p.write_text(outputs[p], encoding='utf-8', newline='\n')
    print(f'unified equations: 18 skills, 18 traits, 324 pairs, 36 signatures, 6 unifications; wrote {len(stale)} file(s)')


if __name__ == '__main__':
    main()
