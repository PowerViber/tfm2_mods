"""Generate Basalt's Rust tables, champion data, tooltips, editor data and roster entry from rules/basalt.json.

Change numbers in the rules file and rerun; never edit the outputs by hand. `--check` only verifies.
"""
from pathlib import Path
import copy, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'rules/basalt.json').read_text())
ID = rules['id']
GROUPS = ['basic', 'wall', 'slam', 'jump', 'pull', 'punch', 'airDash', 'hurl', 'slab', 'clap', 'swing', 'ult', 'ai']


def snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).upper()


lines = ['//! Generated by tools/generate-basalt.py from rules/basalt.json. Do not edit by hand.', '#![allow(dead_code)]', '',
         'pub const RULES_REVISION: &str = ' + json.dumps(rules['revision']) + ';',
         f'pub const MOD_POWER: [i32; 7] = {rules["modPower"]};']
for group in GROUPS:
    for k, v in rules[group].items():
        lines.append(f'pub const {snake(group)}_{snake(k)}: i64 = {v};')
lines.append(f'pub const FX_TOKENS: usize = {rules["fxTokens"]};')
rust = '\n'.join(lines) + '\n'

b, w, sl, j, pu, pn, ad, hu, sb, cl, sw, ul, _ = (rules[k] for k in GROUPS)
sec = lambda n: f'{n / 60:g} s'
text = {
    'name': rules['name'],
    'skill': (f"Bedrock (passive): Basalt keeps up to {w['max']} walls ({w['length']} long). A wall stays while he is within {w['keepRange']} of it and fades "
              f"{sec(w['fadeTicks'])} after he leaves that range. Only he can hit his walls: each takes {w['integrity']} of his hits (a punch, a Hurl landing, an enemy "
              f"slammed into it) and then shatters into rubble (+{w['rubblePct']}% on his next whip). Any enemy his skills drive into a wall (his or the map's) is "
              f"slammed: stunned {sec(sl['stunTicks'])} and {sl['base']} + {sl['adRatio']}% Attack (once every {sec(sl['repeatTicks'])} per target). "
              f"Jump (passive, {j['charges']} charges, {sec(j['rechargeTicks'])} each): a {j['range']} leap, airborne {sec(j['airTicks'])} (crowd-control immune, "
              f"passes every wall), with one free double jump; kicking off one of his walls goes {j['kickJump']} and restores the double jump. "
              f"Whip Pull (passive, {sec(pu['cooldownTicks'])}): his whip catches any wall within {pu['range']} and slingshots him over it, faster the farther he is "
              f"({pu['speedBase']} + distance / {pu['speedDivisor']} per tick), landing {pu['overshootPct']}% of the distance past it, airborne all the way. "
              f"S1 Raise & Punch ({pn['charges']} charges, {sec(pn['rechargeTicks'])} each): a wall rises in front of him and his punch launches it {pn['slide']} "
              f"forward, pushing enemies ({pn['base']} + {pn['adRatio']}% Attack) and slamming anyone pinned. In the air: Air Dash, a {ad['range']} dash that keeps "
              f"him airborne and can be followed by anything."),
    'skill2': (f"Hurl ({sec(hu['cooldownTicks'])}): his whip lashes his nearest wall or rips a chunk off terrain within {hu['grabRange']} and throws it onto a point "
               f"within {hu['range']}: enemies within {hu['radius']} take {hu['base']} + {hu['adRatio']}% Attack and are knocked outward (into walls: slammed); the "
               f"wall stands where it lands. In the air: Slab Drop, a wall thrown down within {sb['range']}, knocking up everyone within {sb['radius']} for "
               f"{sec(sb['knockTicks'])} ({sb['base']} + {sb['adRatio']}% Attack). "
               f"Crushing Clap ({sec(cl['cooldownTicks'])}): two walls rise in a {cl['coneDeg']}° V in front of him and his whip snaps them shut; enemies inside are "
               f"swept to the middle, take {cl['base']} + {cl['adRatio']}% Attack and are stunned {sec(cl['stunTicks'])}; the walls fuse into one. In the air: "
               f"Whip Swing, his whip snares an enemy champion within {sw['range']}, grows up to {sw['maxRadius']} while he swings them a full turn and more, and "
               f"slams them ({sw['base']} + {sw['adRatio']}% Attack) toward a teammate (or away from their team) into a wall there, raising one if needed."),
    'ult': (f"Boulder Throw ({sec(ul['cooldownTicks'])}): he stands and charges for {sec(ul['chargeTicks'])}, then throws a massive rock anywhere on the map. "
            f"Enemies within {ul['radius']} of the impact are knocked up {sec(ul['knockTicks'])}, slowed {ul['slowPct']}% for {sec(ul['slowTicks'])} and take "
            f"{ul['base']} + {ul['adRatio']}% Attack; the rock stands as one of his walls. In the air: Meteor Punch, he hangs in the air charging for "
            f"{sec(ul['chargeTicks'])}, then punches the rock apart and {ul['meteorCount']} burning meteors rain on the area: each knocks up briefly, slows "
            f"{ul['meteorSlowPct']}% and burns for {sec(ul['burnTicks'])}. Recast within {sec(ul['recastTicks'])} of the landing: his whip catches the rock and "
            f"slingshots him to where it landed. His skills never hit towers."),
}

champ = copy.deepcopy(json.loads((ROOT / 'mods/tfm2_custom/champion/tfm2_custom_contender.data_champion').read_text()))
# placeholder body until Codex's art: Grimhald's sheet (an original melee bruiser)
sprite = 'asset/tfm2_custom/champions/' + ID
if not (ROOT / f'mods/tfm2_custom/champions/{ID}#sheet.png').exists():
    sprite = 'asset/tfm2_custom/champions/tfm2_custom_grimhald'
champ.update(id=ID, category=rules['category'], tags=rules['tags'], sprite=sprite, anim_prefix='')
for key in ['stat', 'growth']:
    champ[key] = {k: 0 for k in champ[key]}
    champ[key].update(rules[key])
champ['attack'].update(duration=b['duration'], cooltime=b['cooldownTicks'], start_timing=b['startTiming'], range=b['range'],
                       effect={'type': 'Attack', 'damage': 0, 'attack_ratio': 100})
for slot in ['skill', 'skill2', 'ult']:
    champ[slot]['description'] = '#asset/base/text/champion?description.' + ID + '.' + slot
champ['passive'] = {'passive_ref': 'tfm2_custom_ai:basalt', 'params': {}}
champ['passive_ult'] = {'passive_ref': 'tfm2_custom_ai:ult_learned', 'params': {}}
VFX = 'asset/tfm2_custom/vfx/basalt'
# his own effects arrive with Codex's sheet (`docs/basalt-art-handoff.md`); until then every name he plays is bound to
# existing Grimhald and Kicker effects so the walls, throws and slams are visible in a playtest
PLACEHOLDER = {'block': ('grimhald', 'cage_block'), 'rise': ('grimhald', 'pillar_rise'), 'break': ('grimhald', 'pillar_break'),
               'slam': ('grimhald', 'slam'), 'leap': ('grimhald', 'leap'), 'land': ('grimhald', 'land'), 'dust': ('grimhald', 'bash_dust'),
               'rock': ('kicker', 'rock_hit'), 'wall_slam': ('kicker', 'wall_slam'), 'dash': ('kicker', 'dash')}
if (ROOT / 'mods/tfm2_custom/vfx/basalt#sheet.png').exists():
    champ['view_effects'] = [dict(type='Animation', name='bs_' + e, anim=VFX, tag=e, z=5, is_follow=False) for e in PLACEHOLDER]
else:
    champ['view_effects'] = [dict(type='Animation', name='bs_' + e, anim='asset/tfm2_custom/vfx/' + sheet, tag=tag, z=-2 if e in ('land', 'dust') else 5,
                                  is_follow=False) for e, (sheet, tag) in PLACEHOLDER.items()]
champ['view_buffs'] = []

data = json.dumps(champ, indent=2) + '\n'

roster = dict(id=ID, name=rules['name'], family='original', role='Fighter', native=True,
              basicAttack=dict(name='Stone Whip', kind='melee', range=b['range']),
              skills=[dict(slot='skill', name='Bedrock / Jump / Whip Pull / Raise & Punch / Air Dash', kinds=['Dash', 'Cc', 'Aoe'],
                           intents=['Engage', 'Escape'], summary=text['skill']),
                      dict(slot='skill2', name='Hurl / Slab Drop / Crushing Clap / Whip Swing', kinds=['Projectile', 'Cc', 'Aoe'],
                           intents=['Engage', 'Clear'], summary=text['skill2']),
                      dict(slot='ult', name='Boulder Throw / Meteor Punch', kinds=['Projectile', 'Aoe', 'Cc'], intents=['Engage'], summary=text['ult'])])

outputs = {
    ROOT / 'editor/basalt-data.js': 'window.BASALT_RULES = ' + json.dumps(rules, separators=(',', ':')) + ';\n',
    ROOT / 'native/tfm2_custom_ai/src/basalt_data.rs': rust,
    ROOT / 'mods/tfm2_custom/champion' / f'{ID}.data_champion': data,
}
check = '--check' in sys.argv
stale = [str(p) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
i18n = ROOT / 'mods/tfm2_custom/text/champion.i18n'
loc = json.loads(i18n.read_text(encoding='utf8'))
roster_p = ROOT / 'rules/champions.json'
r = json.loads(roster_p.read_text(encoding='utf8'))
if loc['en']['description'].get(ID) != text:
    stale.append(str(i18n))
if next((c for c in r['champions'] if c['id'] == ID), None) != roster:
    stale.append(str(roster_p))
if check:
    if stale:
        sys.exit('stale: ' + ', '.join(stale))
    print('Basalt outputs are current')
    sys.exit(0)
for p_, s in outputs.items():
    p_.write_text(s)
loc['en']['description'][ID] = text
i18n.write_text(json.dumps(loc, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
existing = [c['id'] for c in r['champions']]
if ID in existing:
    r['champions'] = [roster if c['id'] == ID else c for c in r['champions']]
else:
    r['champions'].append(roster)
roster_p.write_text(json.dumps(r, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
print('Basalt data, tooltips, editor data and roster entry generated')
