"""Canonical development and bounded planner constants, shared by every native/WASM build."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
d=json.loads((root/'rules/universal-ai.json').read_text(encoding='utf8'))
lines=['// Generated by tools/generate-universal-rules.py.']
for group in ['development','planning']:
 for k,v in d[group].items():
  import re
  name=re.sub(r'(?<!^)(?=[A-Z])','_',k).upper()
  lines.append(f'pub const {name}: usize = {v};')
lines.append(f'pub const INITIAL_OFFSET: i64 = {d["initializationOffset"]};')
(root/'native/tfm2_custom_ai/src/universal_data.rs').write_text('\n'.join(lines)+'\n',encoding='utf8')
(root/'editor/universal-data.js').write_text('window.UNIVERSAL_RULES='+json.dumps(d,separators=(',',':'))+';\n',encoding='utf8')
print('Universal rules v2 generated')
