"""Generate the champion roster from rules/champions.json.

Writes native/tfm2_custom_ai/src/roster_data.rs, editor/roster.js and docs/champions.md.
`--check` only verifies that the generated files are up to date.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'rules/champions.json'
OUT_RS = ROOT / 'native/tfm2_custom_ai/src/roster_data.rs'
OUT_JS = ROOT / 'editor/roster.js'
OUT_MD = ROOT / 'docs/champions.md'
SLOTS = {'skill': 'Skill', 'skill2': 'Skill2', 'ult': 'Ult'}
SLOT_LABEL = {'skill': 'S1', 'skill2': 'S2', 'ult': 'Ult'}


def rs_str(s):
    return json.dumps(s, ensure_ascii=False)


def mask(names, order):
    bad = [n for n in names if n not in order]
    if bad:
        raise SystemExit(f'unknown label(s) {bad}; allowed: {order}')
    return ' | '.join(f'{1 << order.index(n)}' for n in names) or '0'


def validate(doc):
    ids = set()
    for c in doc['champions']:
        if c['id'] in ids:
            raise SystemExit(f'duplicate champion {c["id"]}')
        ids.add(c['id'])
        if c['family'] not in doc['families']:
            raise SystemExit(f'{c["id"]}: unknown family {c["family"]}')
        if not c['skills']:
            raise SystemExit(f'{c["id"]}: no skills')
        for s in c['skills']:
            if s['slot'] not in SLOTS:
                raise SystemExit(f'{c["id"]}: bad slot {s["slot"]}')
            if not s['intents'] or not s['kinds']:
                raise SystemExit(f'{c["id"]}/{s["name"]}: every skill needs a kind and an intent')
    for r in doc['familyRules']:
        for f in (r['from'], r['to']):
            if f != '*' and f not in doc['families']:
                raise SystemExit(f'family rule {r["id"]}: unknown family {f}')


def rust(doc):
    K, I = doc['kinds'], doc['intents']
    fams = list(doc['families'])
    out = ['// Generated by tools/generate-roster.py from rules/champions.json. Do not edit.',
           'use crate::roster::{ChampionDef, FamilyDef, FamilyRule, SkillDef, BasicAttack, Range};',
           'use mod_api_stable::SkillSlotV1 as Slot;', '']
    out.append('/// The label order the bit masks use; a test checks it matches `roster::Kind` and `roster::Intent`.')
    out.append('#[cfg(test)]')
    out.append(f'pub const KINDS: [&str; {len(K)}] = [{", ".join(rs_str(k) for k in K)}];')
    out.append('#[cfg(test)]')
    out.append(f'pub const INTENTS: [&str; {len(I)}] = [{", ".join(rs_str(i) for i in I)}];')
    out.append(f'pub static FAMILIES: [FamilyDef; {len(fams)}] = [')
    for k in fams:
        f = doc['families'][k]
        out.append(f'    FamilyDef {{ key: {rs_str(k)}, name: {rs_str(f["name"])}, about: {rs_str(f["about"])} }},')
    out.append('];')
    out.append(f'pub static FAMILY_RULES: [FamilyRule; {len(doc["familyRules"])}] = [')
    for r in doc['familyRules']:
        out.append(f'    FamilyRule {{ id: {rs_str(r["id"])}, from: {rs_str(r["from"])}, to: {rs_str(r["to"])}, '
                   f'rule: {rs_str(r["rule"])} }},')
    out.append('];')
    out.append(f'pub static CHAMPIONS: [ChampionDef; {len(doc["champions"])}] = [')
    for c in doc['champions']:
        ba = c['basicAttack']
        out.append(f'    ChampionDef {{ id: {rs_str(c["id"])}, name: {rs_str(c["name"])}, family: {fams.index(c["family"])}, '
                   f'role: {rs_str(c["role"])}, native: {str(c["native"]).lower()}, '
                   f'basic: BasicAttack {{ name: {rs_str(ba["name"])}, range: {ba["range"]}, '
                   f'reach: Range::{"Melee" if ba["kind"] == "melee" else "Ranged"} }}, skills: &[')
        for s in c['skills']:
            out.append(f'        SkillDef {{ slot: Slot::{SLOTS[s["slot"]]}, name: {rs_str(s["name"])}, '
                       f'kinds: {mask(s["kinds"], K)}, intents: {mask(s["intents"], I)} }},')
        out.append('    ] },')
    out.append('];')
    return '\n'.join(out) + '\n'


def js(doc):
    slim = {k: doc[k] for k in ('kinds', 'intents', 'families', 'familyRules', 'champions')}
    return ('/* Generated by tools/generate-roster.py from rules/champions.json. Do not edit. */\n'
            'window.TFM2_ROSTER = ' + json.dumps(slim, ensure_ascii=False, separators=(',', ':')) + ';\n')


def markdown(doc):
    fams = doc['families']
    lines = ['# Champions', '',
             '_Generated by `tools/generate-roster.py` from `rules/champions.json`. Edit the JSON, then rerun the tool._', '',
             'Each champion reads as **champion – family – skills – basic attack**. A skill lists what it is (its kinds) '
             'and what an athlete uses it for (its intents):', '',
             '- **Kinds:** ' + ', '.join(doc['kinds']) + '.',
             '- **Intents:** ' + ', '.join(doc['intents']) + '.', '',
             'Custom champions are labelled by hand. Base-game labels are derived from the game\'s own skill text and '
             'the farming catalogue, so treat them as a first pass.', '',
             'The same data answers questions in code: `roster::can(name, Intent::Escape)`, '
             '`roster::skills_for(name, Intent::Clear)` and `roster::champions_with(Kind::Dash)`.', '',
             '## Who can do what', '', '| Intent | Champions |', '|---|---|']
    for intent in doc['intents']:
        who = [c['name'] for c in doc['champions'] if any(intent in s['intents'] for s in c['skills'])]
        lines.append(f'| {intent} | {len(who)}: {", ".join(who)} |')
    lines += ['', '## Families', '', '| Family | Champions | About |', '|---|---|---|']
    for k, f in fams.items():
        who = [c['name'] for c in doc['champions'] if c['family'] == k]
        shown = ', '.join(who) if len(who) <= 8 else f'{len(who)} base-game champions'
        lines.append(f'| {f["name"]} | {shown} | {f["about"]} |')
    lines += ['', '## Family rules', '',
              'These are the rules that already apply across franchises. They are listed here; the code at each site applies them.', '',
              '| Rule | From | To | What happens | Where |', '|---|---|---|---|---|']
    for r in doc['familyRules']:
        to = 'everyone' if r['to'] == '*' else fams[r['to']]['name']
        lines.append(f'| {r["id"]} | {fams[r["from"]]["name"]} | {to} | {r["rule"]} | `{r["site"]}` |')
    for title, native in (('Custom champions', True), ('Base-game champions', False)):
        lines += ['', f'## {title}', '']
        for c in sorted((c for c in doc['champions'] if c['native'] == native), key=lambda c: c['name']):
            ba = c['basicAttack']
            lines.append(f'### {c["name"]} – {fams[c["family"]]["name"]} – {c["role"]}')
            lines.append('')
            lines.append(f'- **Basic attack:** {ba["name"]} ({ba["kind"]}, range {ba["range"]})')
            for s in c['skills']:
                lines.append(f'- **{SLOT_LABEL[s["slot"]]} · {s["name"]}** [{", ".join(s["kinds"])} | '
                             f'{", ".join(s["intents"])}]: {s["summary"]}')
            lines.append('')
    return '\n'.join(lines).rstrip() + '\n'


def main():
    doc = json.loads(SRC.read_text(encoding='utf-8'))
    validate(doc)
    outputs = {OUT_RS: rust(doc), OUT_JS: js(doc), OUT_MD: markdown(doc)}
    if '--check' in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items()
                 if not p.exists() or p.read_text(encoding='utf-8') != text]
        if stale:
            raise SystemExit('roster: stale ' + ', '.join(stale) + ' (run python3 tools/generate-roster.py)')
        print('roster: up to date')
        return
    for p, text in outputs.items():
        p.write_text(text, encoding='utf-8', newline='\n')
    n = len(doc['champions'])
    print(f'roster: {n} champions, {sum(len(c["skills"]) for c in doc["champions"])} skills, '
          f'{len(doc["familyRules"])} family rules')


if __name__ == '__main__':
    main()
