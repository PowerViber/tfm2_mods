 approvals=json.loads((OUT/'approval.json').read_text()).get('bodies',{}) if (OUT/'approval.json').exists() else {}
 approved=approvals.get(name,{})
 report={'name':name,'approval':'appearance approved' if approved.get('approved') and approved.get('sourceSha256')==sha(folder/'proposal-source.png') else 'pending','runtimeUnchanged':True,'sourceSha256':sha(folder/'proposal-source.png'),'sizeCorrection':'2026-10-30: Reihan requested game-size height; use original visible idle height and flag symmetric preview padding rather than shrinking the whole character. Padding is not integrated.','extraction':'Connected alpha bounds >=128, isolated from neighbouring cells with one source-pixel edge margin; unchanged colour/alpha of selected pixels, one character-wide nearest-neighbour scale, original world foot baseline','frames':records}
