def components(im,count=8,columns=4):
 """Locate sprite bounds using alpha; preserve source pixels inside each crop."""
 a=np.asarray(im.getchannel('A'))>=128
 seen=np.zeros(a.shape,dtype=np.uint32); groups=[];h,w=a.shape;component_id=0
 for y,x in zip(*np.nonzero(a)):
  if seen[y,x]:continue
  component_id+=1
  todo=[(int(x),int(y))];seen[y,x]=component_id;pixels=0;x0=x1=int(x);y0=y1=int(y)
  while todo:
   xx,yy=todo.pop();pixels+=1;x0=min(x0,xx);x1=max(x1,xx);y0=min(y0,yy);y1=max(y1,yy)
   for dy in (-1,0,1):
    for dx in (-1,0,1):
     nx,ny=xx+dx,yy+dy
     if 0<=nx<w and 0<=ny<h and a[ny,nx] and not seen[ny,nx]:seen[ny,nx]=component_id;todo.append((nx,ny))
  if pixels>100: groups.append({'pixels':pixels,'box':[x0,y0,x1+1,y1+1],'component':component_id})
 groups=sorted(groups,key=lambda v:v['pixels'],reverse=True)[:count]
 assert len(groups)==count,('Unexpected separated sprite count',count,groups)
 groups.sort(key=lambda v:(v['box'][1]+v['box'][3])/2)
 groups=[g for n in range(0,count,columns) for g in sorted(groups[n:n+columns],key=lambda v:v['box'][0])]
 assert min(g['pixels'] for g in groups)>max(g['pixels'] for g in groups)*.15,'A pose may have merged or split'
 return groups,seen

def component_crop(im,group,labels):
 """Exclude neighbouring packing cells, retaining the selected sprite's pixels."""
 x0,y0,x1,y1=group['box'];lab=labels[y0:y1,x0:x1]
 keep=Image.fromarray(np.where(lab==group['component'],255,0).astype('uint8')).filter(ImageFilter.MaxFilter(3))
 pixels=np.asarray(im.crop(group['box'])).copy()
 pixels[:,:,3][(np.asarray(keep)==0)|((lab!=0)&(lab!=group['component']))]=0
 return Image.fromarray(pixels)

def foot_x(im):
 a=np.asarray(im.getchannel('A'))>=128
 if not a.any():a=np.asarray(im.getchannel('A'))>0
 if not a.any():return im.width/2
 y=np.nonzero(a)[0].max();xs=np.nonzero(a[max(0,y-2):y+1])[1]
 return float(xs.mean()) if len(xs) else im.width/2

def sprite_library(path,count):
 im=Image.open(path).convert('RGBA');groups,labels=components(im,count)
 return [component_crop(im,g,labels) for g in groups]

def pose_choice(name,tag,n,count):
 """Map new authored keys onto the existing complete animation timelines."""
 if tag=='dead':return ('m',min(15,12+n*4//max(1,count)))
 if tag=='hit':return ('m',11)
 if tag=='run' or tag.endswith('_run') or tag=='skill2_dash':
  return [('p',2),('m',0),('m',1),('m',2),('p',3),('m',3),('m',4),('m',5)][n%8]
 if tag=='attack' or tag.endswith('_attack') or tag=='_attack_fixed':
  seq=[('p',4),('m',6),('p',5),('m',7),('p',4)];return seq[min(len(seq)-1,n*len(seq)//max(1,count))]
 if tag in ['idle','vampire_base']:return ('p',[0,1,1,0][n%4])
 special=10 if tag.startswith('ult') else 9 if tag=='skill2' else 8
 if name=='stark': special=9 if tag.startswith('ult') else 10 if tag=='skill2' else 8
 return ('p',0) if n==0 or n==count-1 else ('m',special)

def fit_pose(im,reference,scale):
 """Symmetric padding preserves exact original world/foot anchors, never shrinks."""
 box=reference.getbbox()
 if box is None:return Image.new('RGBA',reference.size),(0,0)
 size=(max(1,round(im.width*scale)),max(1,round(im.height*scale)));small=im.resize(size,Image.Resampling.NEAREST)
 if small.getbbox() is not None:small=small.crop(small.getbbox())
 x=round(foot_x(reference)-foot_x(small));y=box[3]-small.height
 px=max(0,-x,x+small.width-reference.width);py=max(0,-y,y+small.height-reference.height)
 canvas=Image.new('RGBA',(reference.width+2*px,reference.height+2*py));canvas.alpha_composite(small,(x+px,y+py))
 assert 2*canvas.getbbox()[3]-canvas.height==2*box[3]-reference.height
 return canvas,(px,py)

def atlas_pack(images,metadata):
 """Deterministic shelf pack; keep every frame's timing and dimensions."""
 atlas=Image.new('RGBA',(1024,2048));meta=copy.deepcopy(metadata);x=y=row=0;cache={}
 for tag,anim in meta['anims'].items():
  for n,f in enumerate(anim['frames']):
   im=images[(tag,n)];key=(im.size,hashlib.sha256(im.tobytes()).digest())
   if key not in cache:
    if x+im.width>1024:x=0;y+=row+1;row=0
    assert y+im.height<=2048,('Atlas budget exceeded',tag,n)
    cache[key]={'x':x,'y':y,'w':im.width,'h':im.height};atlas.alpha_composite(im,(x,y));x+=im.width+1;row=max(row,im.height)
   f['data']=cache[key].copy()
 return atlas.crop((0,0,1024,max(1,y+row))),meta

def complete(name):
 folder=OUT/name;approval=json.loads((OUT/'approval.json').read_text());allowed=approval['bodies'].get(name,{})
 assert allowed.get('approved') and allowed['sourceSha256']==sha(folder/'proposal-source.png'),'Appearance approval must match source'
 assert approval.get('paddingException'),'Full-size padding requires the recorded exception'
 p=sprite_library(folder/'proposal-source.png',8);m=sprite_library(folder/'motion-source.png',16)
 old,meta=source(name);idle=crop_frame(old,meta['anims']['idle']['frames'][0]);height=idle.getbbox()[3]-idle.getbbox()[1]
 scales={'p':height/p[0].height,'m':height/statistics.median(im.height for im in m[:6])}
 images={};records=[];pure=0
 for tag,anim in meta['anims'].items():
  for n,f in enumerate(anim['frames']):
   before=crop_frame(old,f)
   if tag not in BODY_TAGS[name]:images[(tag,n)]=before;pure+=1;continue
   kind,index=pose_choice(name,tag,n,len(anim['frames']));image=(p if kind=='p' else m)[index]
   result,padding=fit_pose(image,before,scales[kind])
   if before.getbbox() is not None:
    # Retain encoded death opacity. Colour/alpha changes elsewhere are authored art.
    alpha_max=before.getchannel('A').getextrema()[1]
    if alpha_max<255:result.putalpha(result.getchannel('A').point(lambda a:a*alpha_max//255))
   images[(tag,n)]=result
   records.append({'tag':tag,'frame':n,'source':[kind,index],'originalSize':list(before.size),'size':list(result.size),'padding':list(padding),'duration':f['duration'],'worldFoot2':None if before.getbbox() is None else 2*before.getbbox()[3]-before.height})
 atlas,packed=atlas_pack(images,meta);atlas.save(folder/'complete#sheet.png');(folder/'complete#anim.fanim').write_text(json.dumps(packed,separators=(',',':'))+'\n')
 for tag in BODY_TAGS[name]:
  if tag not in meta['anims']:continue
  panels=[];duration=[]
  all_frames=[crop_frame(old,f) for f in meta['anims'][tag]['frames']]+[images[(tag,n)] for n in range(len(meta['anims'][tag]['frames']))]
  max_w=max(im.width for im in all_frames);max_h=max(im.height for im in all_frames)
  cell=max(200,4*max_w+32);height=max(270,3*max_h+70)
  for n,f in enumerate(meta['anims'][tag]['frames']):
   before=crop_frame(old,f);after=images[(tag,n)];panel=Image.new('RGB',(4*cell,height),'#182b2c');d=ImageDraw.Draw(panel)
   d.text((12,8),name+' / '+tag+' / '+str(n+1)+' - current / new right / new left / new light',font=FONT,fill='white')
   for col,(im,flip,bg) in enumerate([(before,False,'#29403b'),(after,False,'#29403b'),(after,True,'#29403b'),(after,False,'#d4d7c2')]):
    if flip:im=ImageOps.mirror(im)
    x=col*cell;d.rectangle((x,35,x+cell-5,height-5),fill=bg)
    # Both images use their frame-centre anchor, exactly like the game.
    panel.paste(im,(x+max_w//2+8-im.width//2,height//2-im.height//2),im)
    zoom=im.resize((im.width*3,im.height*3),Image.Resampling.NEAREST)
    panel.paste(zoom,(x+max_w+16+(cell-max_w-24-zoom.width)//2,40+(height-50-zoom.height)//2),zoom)
   panels.append(panel);duration.append(max(20,round(f['duration']*1000)))
  panels[0].save(folder/(tag+'-complete.gif'),save_all=True,append_images=panels[1:],duration=duration,loop=0,disposal=2)
 report={'name':name,'status':'complete approved-source animation','sourceSha256':sha(folder/'proposal-source.png'),'motionSha256':sha(folder/'motion-source.png'),'atlasSha256':sha(folder/'complete#sheet.png'),'metadataSha256':sha(folder/'complete#anim.fanim'),'frameCount':len(records),'unchangedNonBodyFrames':pure,'decodedBytes':atlas.width*atlas.height*4,'size':[atlas.width,atlas.height],'idleVisibleHeight':idle.getbbox()[3]-idle.getbbox()[1],'scales':scales,'frames':records}
 (folder/'complete.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps({k:report[k]for k in ['name','frameCount','unchangedNonBodyFrames','size','idleVisibleHeight']}))

def preview(name):
 folder=OUT/name;folder.mkdir(exist_ok=True)
 proposed=Image.open(folder/'proposal-source.png').convert('RGBA');groups,labels=components(proposed)
 frames=[component_crop(proposed,g,labels) for g in groups]
 old,meta=source(name);cast=SPECS[name][2]
 tags=['idle','idle','run','run','attack','attack',cast,cast]
 selected=[meta['anims'][tag]['frames'][min(n%2,len(meta['anims'][tag]['frames'])-1)] for n,tag in enumerate(tags)]
 existing=[crop_frame(old,f) for f in selected]
 # Preserve the existing idle height. Never shrink all poses to fit one wide pose.
 # Preview-only symmetric padding exposes poses needing an explicit frame-policy decision.
 scale=(existing[0].getbbox()[3]-existing[0].getbbox()[1])/frames[0].height
 native=[];records=[]
 for n,(im,target) in enumerate(zip(frames,existing)):
  size=(max(1,round(im.width*scale)),max(1,round(im.height*scale)))
  small=im.resize(size,Image.Resampling.NEAREST)
  foot=target.getbbox()[3];desired_x=round(foot_x(target)-foot_x(small));desired_y=foot-small.height
  pad_x=max(0,-desired_x,desired_x+small.width-target.width);pad_y=max(0,-desired_y,desired_y+small.height-target.height)
  xy=(desired_x+pad_x,desired_y+pad_y)
  canvas=Image.new('RGBA',(target.width+2*pad_x,target.height+2*pad_y));canvas.alpha_composite(small,xy);native.append(canvas)
  canvas.save(folder/f'key-{n}.png')
  assert 2*canvas.getbbox()[3]-canvas.height==2*foot-target.height,'World foot anchor changed'
  records.append({'index':n,'tag':tags[n],'sourceBounds':groups[n]['box'],'sourcePixels':groups[n]['pixels'],'frame':selected[n],'nativeSize':list(canvas.size),'originalSize':list(target.size),'previewPadding':[pad_x,pad_y],'poseNeedsRefit':bool(pad_x or pad_y),'paste':list(xy),'scale':scale,'oldFootBaseline':foot,'newFootBaseline':canvas.getbbox()[3]})
 max_w=max(im.width for im in existing+native);max_h=max(im.height for im in existing+native)
 cell=max(208,4*max_w+24);width=5*cell;row=max(220,3*max_h+44)
 contact=Image.new('RGB',(width,55+4*row),'#16232c');d=ImageDraw.Draw(contact)
 d.text((12,8),name.upper()+' - key-pose review only; full animation pending approval',font=FONT,fill='white')
 labels=['Current','Proposal right / dark','Proposal left / dark','Proposal right / light','Proposal left / light']
 for k,label in enumerate(labels):d.text((12+k*cell,30),label,font=FONT,fill='#e1ce9f')
