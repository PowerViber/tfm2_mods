"""Generate v2 constants without changing the frozen v1 rules."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
def generate():
    d=json.loads((ROOT/'rules/gojo-v2.json').read_text(encoding='utf-8'))
    lines=['// Generated by tools/generate-gojo-v2-rules.py; edit rules/gojo-v2.json.']
    for k,v in d.items():
        if type(v) is int: lines.append(f'pub const {k.upper()}: i64 = {v};')
        elif isinstance(v,list) and all(type(x) is int for x in v): lines.append(f'pub const {k.upper()}: [i64; {len(v)}] = {v!r};')
    (ROOT/'native/tfm2_custom_ai/src/gojo_v2_data.rs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    (ROOT/'editor/gojo-data.js').write_text('window.GOJO_RULES='+json.dumps(d,separators=(',',':'))+';\n',encoding='utf-8')
if __name__=='__main__': generate()
