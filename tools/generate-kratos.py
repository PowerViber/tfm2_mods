"""Generate Kratos's Rust tables, champion data, tooltips, editor data, roster entry and family from rules/kratos.json.

Change numbers in the rules file and rerun; never edit the outputs by hand. `--check` only verifies.
"""
from pathlib import Path
import copy, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'rules/kratos.json').read_text())
ID = rules['id']
GROUPS = ['basic', 'passive', 'sight', 'rampage', 'guard', 'dash', 'link', 'fenrir', 'immune', 'ai']
FAMILY = ('gow', {'name': 'God of War', 'about': 'Two god-slaying weapons, frost and fire; Spartan rage and Norse beasts.'})


def snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).upper()


lines = ['//! Generated by tools/generate-kratos.py from rules/kratos.json. Do not edit by hand.', '#![allow(dead_code)]', '',
         'pub const RULES_REVISION: &str = ' + json.dumps(rules['revision']) + ';',
         f'pub const MOD_POWER: [i32; 7] = {rules["modPower"]};']
for group in GROUPS:
    for k, v in rules[group].items():
        lines.append(f'pub const {snake(group)}_{snake(k)}: i64 = {v};')
lines.append(f'pub const FX_TOKENS: usize = {rules["fxTokens"]};')
rust = '\n'.join(lines) + '\n'

b, p, si, ra, gu, da, li, fe, im = (rules[k] for k in GROUPS[:-1])
sec = lambda n: f'{n / 60:g} s'
text = {
    'name': rules['name'],
    'skill': (f"Frost & Flame (passive): he holds the Leviathan Axe or the Blades of Chaos and changes weapons only through his third skill. "
              f"Axe hits add Frost (at {p['frostStacks']} stacks the target freezes {sec(p['freezeTicks'])}, then can't freeze again for "
              f"{sec(p['freezeImmuneTicks'])}); Blade hits burn for {p['burnBase']} + {p['burnAdRatio']}% Attack a second for {sec(p['burnTicks'])} "
              f"and his basic attacks reach {b['bladesRange']} instead of {b['axeRange']}. Spartan Armor: every weapon swap gives a shield of "
              f"{p['swapShieldPct']}% of his max HP for {sec(p['swapShieldTicks'])}, up to {p['swapShieldCapPct']}%. "
              f"Heimdall's Sight ({sec(si['cooldownTicks'])}): for {sec(si['ticks'])} he can't be crowd-controlled and dodges the first hit "
              f"from each enemy champion."),
    'skill2': (f"Leviathan Rampage ({sec(ra['cooldownTicks'])}): three advancing swings over about {sec(3 * ra['stageTicks'])}, stopped by walls: "
               f"an axe cleave ({ra['cleaveBase']} + {ra['cleaveAdRatio']}% Attack, Frost, {ra['slowPct']}% slow), a Blades sweep "
               f"({ra['sweepBase']} + {ra['sweepAdRatio']}% Attack, burn) and a frost-and-fire smash (radius {ra['smashRadius']}, "
               f"{ra['smashBase']} + {ra['smashAdRatio']}% Attack, knock-up {sec(ra['knockUpTicks'])}). It cleanses him, and during it he "
               f"can't be crowd-controlled and takes {ra['reducePct']}% less damage. "
               f"Spartan Guard ({sec(gu['cooldownTicks'])}, swaps to the axe): cleanses, a shield of {gu['shieldPct']}% max HP for "
               f"{sec(gu['shieldTicks'])} and {sec(gu['immuneTicks'])} of crowd-control immunity. "
               f"Chain Dash ({sec(da['cooldownTicks'])}, swaps to the Blades): throws the Blades {da['range']}; on a champion, minion or creep "
               f"he dashes to it through any wall and strikes ({da['base']} + {da['adRatio']}% Attack). Guard then Dash within "
               f"{sec(li['windowTicks'])}: the Dash reaches {da['linkedRange']}. Dash then Guard: {sec(gu['linkedImmuneTicks'])} of immunity and "
               f"a {gu['linkedShieldPct']}% shield. Crowd-control immunity lasts at most {sec(im['capTicks'])} in any {sec(im['windowTicks'])}."),
    'ult': (f"Fenrir's Charge ({sec(fe['cooldownTicks'])}): Fenrir appears {fe['distance']} away and charges back to Kratos, hitting enemies "
            f"on the way ({fe['base']} + {fe['adRatio']}% Attack, {fe['slowPct']}% slow for {sec(fe['slowTicks'])}). Recast within "
            f"{sec(fe['recastTicks'])}: Kratos leaps into the wolf (up to {fe['dashMax']}) and slams it back ({fe['returnBase']} + "
            f"{fe['returnAdRatio']}% Attack, knock-up {sec(fe['knockUpTicks'])}). His skills and Fenrir never hit towers."),
}

champ = copy.deepcopy(json.loads((ROOT / 'mods/tfm2_custom/champion/tfm2_custom_contender.data_champion').read_text()))
# his own body sheet (Codex's art); like Wright, the game skips him until it exists
champ.update(id=ID, category=rules['category'], tags=rules['tags'], sprite='asset/tfm2_custom/champions/' + ID, anim_prefix='')
for key in ['stat', 'growth']:
    champ[key] = {k: 0 for k in champ[key]}
    champ[key].update(rules[key])
champ['attack'].update(duration=b['duration'], cooltime=b['cooldownTicks'], start_timing=b['startTiming'], range=b['axeRange'],
                       effect={'type': 'Attack', 'damage': 0, 'attack_ratio': 100})
for slot in ['skill', 'skill2', 'ult']:
    champ[slot]['description'] = '#asset/base/text/champion?description.' + ID + '.' + slot
champ['passive'] = {'passive_ref': 'tfm2_custom_ai:kratos', 'params': {}}
champ['passive_ult'] = {'passive_ref': 'tfm2_custom_ai:ult_learned', 'params': {}}
VFX = 'asset/tfm2_custom/vfx/kratos'
EFFECTS = (['cleave', 'cleave_l', 'sweep', 'sweep_l', 'smash', 'chain', 'chain_hit', 'dash_trail', 'guard', 'sight', 'swap_axe',
            'swap_blades', 'freeze', 'knock_up', 'fenrir_spawn', 'fenrir_slam', 'fenrir_fade']
           + [f'fenrir_p{i}' for i in range(8)])
GROUND = ('smash', 'fenrir_spawn')
champ['view_effects'] = [dict(type='Animation', name='krt_' + e, anim=VFX, tag=e, z=-2 if e in GROUND else 6, is_follow=False) for e in EFFECTS]
champ['view_buffs'] = ([dict(type='Animated', name='krt_burn', anim=VFX, tag='burn', z=4),
                        dict(type='Animated', name='krt_frozen', anim=VFX, tag='frozen', z=4),
                        dict(type='Animated', name='krt_sight', anim=VFX, tag='sight_aura', z=5),
                        dict(type='Animated', name='krt_guard', anim=VFX, tag='guard_aura', z=5)]
                       + [dict(type='Animated', name=f'krt_frost:{i}', anim=VFX, tag=f'frost{i}', z=4) for i in range(1, p['frostStacks'])])
art_path = ROOT / 'docs/kratos-art-review/art-manifest.json'
if art_path.exists():
    art = json.loads(art_path.read_text())
    if not art['review_only']:
        champ['view_effects'] = [dict(type='Animation', name='krt_' + tag, anim=VFX, tag=tag, z=spec['z'], is_follow=spec.get('follow', False))
                                 for tag, spec in art['effects'].items() if spec['kind'] == 'effect']
if not (ROOT / 'mods/tfm2_custom/vfx/kratos#sheet.png').exists():
    # no VFX sheet yet: the effects stay native-only (nothing drawn) rather than point at a missing sheet
    champ['view_effects'], champ['view_buffs'] = [], []
data = json.dumps(champ, indent=2) + '\n'

roster = dict(id=ID, name=rules['name'], family=FAMILY[0], role='Melee', native=True,
              basicAttack=dict(name='Leviathan Axe / Blades of Chaos', kind='melee', range=b['axeRange']),
              skills=[dict(slot='skill', name="Frost & Flame / Heimdall's Sight", kinds=['Buff', 'Cc'], intents=['Engage', 'Protect'], summary=text['skill']),
                      dict(slot='skill2', name='Leviathan Rampage / Spartan Guard / Chain Dash', kinds=['Dash', 'Aoe', 'Line', 'Shield', 'Cc'],
                           intents=['Engage', 'Escape', 'Protect', 'Clear'], summary=text['skill2']),
                      dict(slot='ult', name="Fenrir's Charge", kinds=['Line', 'Dash', 'Cc'], intents=['Engage'], summary=text['ult'])])

outputs = {
    ROOT / 'editor/kratos-data.js': 'window.KRATOS_RULES = ' + json.dumps(rules, separators=(',', ':')) + ';\n',
    ROOT / 'native/tfm2_custom_ai/src/kratos_data.rs': rust,
    ROOT / 'mods/tfm2_custom/champion' / f'{ID}.data_champion': data,
}
check = '--check' in sys.argv
stale = [str(p) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
i18n = ROOT / 'mods/tfm2_custom/text/champion.i18n'
loc = json.loads(i18n.read_text(encoding='utf8'))
roster_p = ROOT / 'rules/champions.json'
r = json.loads(roster_p.read_text(encoding='utf8'))
if loc['en']['description'].get(ID) != text:
    stale.append(str(i18n))
if next((c for c in r['champions'] if c['id'] == ID), None) != roster or r['families'].get(FAMILY[0]) != FAMILY[1]:
    stale.append(str(roster_p))
if check:
    if stale:
        sys.exit('stale: ' + ', '.join(stale))
    print('Kratos outputs are current')
    sys.exit(0)
for p_, s in outputs.items():
    p_.write_text(s)
loc['en']['description'][ID] = text
i18n.write_text(json.dumps(loc, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
r['families'][FAMILY[0]] = FAMILY[1]
r['champions'] = [c for c in r['champions'] if c['id'] != ID] + [roster]
roster_p.write_text(json.dumps(r, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
print('Kratos data, tooltips, editor data, roster entry and family generated')
