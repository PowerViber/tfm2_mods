"""Generate Kicker's Rust tables, champion data, tooltips, editor data and roster entry from rules/kicker.json.

Change numbers in the rules file and rerun; never edit the outputs by hand. `--check` only verifies.
"""
from pathlib import Path
import copy, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'rules/kicker.json').read_text())
ID = rules['id']
GROUPS = ['basic', 'roof', 'dropIn', 'hop', 'dash', 'bruised', 'rock', 'kick', 'skyfall', 'ult', 'ai']


def snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).upper()


lines = ['//! Generated by tools/generate-kicker.py from rules/kicker.json. Do not edit by hand.', '#![allow(dead_code)]', '',
         'pub const RULES_REVISION: &str = ' + json.dumps(rules['revision']) + ';',
         f'pub const MOD_POWER: [i32; 7] = {rules["modPower"]};']
for group in GROUPS:
    for k, v in rules[group].items():
        lines.append(f'pub const {snake(group)}_{snake(k)}: i64 = {v};')
lines.append(f'pub const FX_TOKENS: usize = {rules["fxTokens"]};')
rust = '\n'.join(lines) + '\n'

b, ro, di, ho, da, br, rk, ki, sk, ul, _ = (rules[k] for k in GROUPS)
sec = lambda n: f'{n / 60:g} s'
text = {
    'name': rules['name'],
    'skill': (f"Rooftop Runner (passive): he can stand and run on walls: {ro['speedPct']}% faster, {ro['reducePct']}% less damage taken, and hidden from "
              f"enemies farther than {ro['hideRange']}. Any jump down is a Drop-in ({sec(di['cooldownTicks'])}): invulnerable while dropping, enemies within "
              f"{di['knockRadius']} of the landing are knocked up for {sec(di['knockTicks'])}, and his next hit deals {di['bonusPct']}% more. Landing on the ground "
              f"also shields him for {ro['groundShieldPctMaxHp']}% max HP ({sec(ro['groundShieldTicks'])}, once every {sec(ro['groundShieldCooldownTicks'])}). "
              f"A stun or knock-up on a wall drops him to the ground. "
              f"Marked Dash ({da['charges']} charges, {sec(da['rechargeTicks'])} each): his hits mark enemies, minions and creeps for {sec(da['markTicks'])} (never a tower); "
              f"he dashes next to a marked unit within {da['range']} and gains a shield of {da['shieldPctMaxHp']}% max HP for {sec(da['shieldTicks'])}. "
              f"Bruised: everyone he crowd-controls is Bruised for {sec(br['ticks'])}: no HP regeneration, {br['healReducePct']}% less healing, and each of his hits adds "
              f"+{br['ampPerStack']}% damage taken (up to {br['maxStacks']} stacks). "
              f"Wall Hop / Drop Kick: onto a wall within {ho['mountRange']} ({sec(ho['mountCooldownTicks'])}); from wall to wall within {ho['wallRange']} "
              f"({ho['charges']} charges, {sec(ho['wallRechargeTicks'])} each on a wall, {sec(ho['groundRechargeTicks'])} on the ground); from a wall, a Drop Kick onto an enemy "
              f"or point within {ho['dropRange']} for {ho['dropBase']} + {ho['dropAdRatio']}% Attack (no charge). With no wall near, a short {ho['groundHop']} hop."),
    'skill2': (f"Rock Throw ({sec(rk['cooldownTicks'])}): a rock flies {rk['range']} in a line through everything (never towers), dealing {rk['base']} + "
               f"{rk['adRatio']}% Attack and marking each unit it hits. From a wall: Rock Rain, {rk['rainCount']} rocks in a narrow fan ({rk['rainRange']}), "
               f"{rk['rainPct']}% damage each. "
               f"Homecoming Kick / Skyfall Kick ({ki['charges']} charges, {sec(ki['rechargeTicks'])} each): on the ground he dashes up to {ki['dashRange']} to an enemy "
               f"champion and kicks it {ki['distance']} away from him for {ki['base']} + {ki['adRatio']}% Attack. The flying body hits up to {ki['secondaryMax']} other "
               f"enemy champions ({ki['secondaryPct']}% damage, knocked up {sec(ki['secondaryKnockTicks'])}); a wall stops it and stuns for {sec(ki['wallStunTicks'])}. "
               f"Flash just before or during the kick re-aims it. From a wall: Skyfall Kick, a {sk['range']} dive that carries the first enemy champion in its line "
               f"to the end, through walls, for {sk['base']} + {sk['adRatio']}% Attack; he lands behind it with a Drop-in."),
    'ult': (f"Second Wind ({sec(ul['cooldownTicks'])}): he sprays a tag where he stands and fights freely for {sec(ul['ticks'])}. If he would die in that time "
            f"he doesn't: he's sent back to the tag with full HP. If the time runs out, he's sent back to the tag with the HP he had when he cast it. "
            f"His skills never hit towers."),
}

champ = copy.deepcopy(json.loads((ROOT / 'mods/tfm2_custom/champion/tfm2_custom_contender.data_champion').read_text()))
# placeholder body until Codex's art: Contender's sheet (original boxer), so the game never skips him
sprite = 'asset/tfm2_custom/champions/' + ID
if not (ROOT / f'mods/tfm2_custom/champions/{ID}#sheet.png').exists():
    sprite = 'asset/tfm2_custom/champions/tfm2_custom_contender'
champ.update(id=ID, category=rules['category'], tags=rules['tags'], sprite=sprite, anim_prefix='')
for key in ['stat', 'growth']:
    champ[key] = {k: 0 for k in champ[key]}
    champ[key].update(rules[key])
champ['attack'].update(duration=b['duration'], cooltime=b['cooldownTicks'], start_timing=b['startTiming'], range=b['range'],
                       effect={'type': 'Attack', 'damage': 0, 'attack_ratio': 100})
for slot in ['skill', 'skill2', 'ult']:
    champ[slot]['description'] = '#asset/base/text/champion?description.' + ID + '.' + slot
champ['passive'] = {'passive_ref': 'tfm2_custom_ai:kicker', 'params': {}}
champ['passive_ult'] = {'passive_ref': 'tfm2_custom_ai:ult_learned', 'params': {}}
VFX = 'asset/tfm2_custom/vfx/kicker'
EFFECTS = ['hop', 'land', 'drop_in', 'rock', 'rock_hit', 'kick', 'kick_trail', 'wall_slam', 'skyfall', 'tag', 'return', 'dash']
GROUND = ('land', 'drop_in', 'tag')
champ['view_effects'] = [dict(type='Animation', name='kk_' + e, anim=VFX, tag=e, z=-2 if e in GROUND else 6, is_follow=False) for e in EFFECTS]
champ['view_buffs'] = ([dict(type='Animated', name='kk_mark', anim=VFX, tag='mark', z=5),
                        dict(type='Animated', name='kk_roof', anim=VFX, tag='roof', z=-1),
                        dict(type='Animated', name='kk_second_wind', anim=VFX, tag='second_wind', z=4)]
                       + [dict(type='Animated', name=f'kk_bruised:{i}', anim=VFX, tag=f'bruised{i}', z=4) for i in range(0, br['maxStacks'] + 1)])
if not (ROOT / 'mods/tfm2_custom/vfx/kicker#sheet.png').exists():
    # no VFX sheet yet: the effects stay native-only (nothing drawn) rather than point at a missing sheet
    champ['view_effects'], champ['view_buffs'] = [], []

data = json.dumps(champ, indent=2) + '\n'

roster = dict(id=ID, name=rules['name'], family='original', role='Fighter', native=True,
              basicAttack=dict(name='Kick', kind='melee', range=b['range']),
              skills=[dict(slot='skill', name='Rooftop Runner / Wall Hop / Drop Kick / Marked Dash', kinds=['Dash', 'Cc', 'Shield'], intents=['Engage', 'Escape'],
                           summary=text['skill']),
                      dict(slot='skill2', name='Rock Throw / Homecoming Kick / Skyfall Kick', kinds=['Projectile', 'Dash', 'Cc'], intents=['Engage', 'Clear', 'Protect'],
                           summary=text['skill2']),
                      dict(slot='ult', name='Second Wind', kinds=['Buff'], intents=['Engage'], summary=text['ult'])])

outputs = {
    ROOT / 'editor/kicker-data.js': 'window.KICKER_RULES = ' + json.dumps(rules, separators=(',', ':')) + ';\n',
    ROOT / 'native/tfm2_custom_ai/src/kicker_data.rs': rust,
    ROOT / 'mods/tfm2_custom/champion' / f'{ID}.data_champion': data,
}
check = '--check' in sys.argv
stale = [str(p) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
i18n = ROOT / 'mods/tfm2_custom/text/champion.i18n'
loc = json.loads(i18n.read_text(encoding='utf8'))
roster_p = ROOT / 'rules/champions.json'
r = json.loads(roster_p.read_text(encoding='utf8'))
if loc['en']['description'].get(ID) != text:
    stale.append(str(i18n))
if next((c for c in r['champions'] if c['id'] == ID), None) != roster:
    stale.append(str(roster_p))
if check:
    if stale:
        sys.exit('stale: ' + ', '.join(stale))
    print('Kicker outputs are current')
    sys.exit(0)
for p_, s in outputs.items():
    p_.write_text(s)
loc['en']['description'][ID] = text
i18n.write_text(json.dumps(loc, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
existing = [c['id'] for c in r['champions']]
if ID in existing:
    r['champions'] = [roster if c['id'] == ID else c for c in r['champions']]
else:
    r['champions'].append(roster)
roster_p.write_text(json.dumps(r, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
print('Kicker data, tooltips, editor data and roster entry generated')
