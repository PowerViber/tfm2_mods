"""Generate Grimhald's Rust tables, champion data, tooltips and roster entry from rules/grimhald.json.

Change numbers in the rules file and rerun; never edit the outputs by hand.
"""
from pathlib import Path
import copy, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'rules/grimhald.json').read_text())
ID = rules['id']


def snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).upper()


# ---- Rust tables
lines = ['//! Generated by tools/generate-grimhald.py from rules/grimhald.json. Do not edit by hand.',
         '#![allow(dead_code)]', '']
lines.append('pub const RULES_REVISION: &str = '+json.dumps(rules.get('revision','grimhald-1'))+';')
lines.append(f'pub const MOD_POWER: [i32; 7] = {rules["modPower"]};')
for group in ['basic', 'passive', 'ghost', 'bulwark', 'bash', 'ult', 'unarmed', 'aura', 'presentation']:
    for k, v in rules[group].items():
        name = f'{group.upper()}_{snake(k)}'
        if isinstance(v, list):
            lines.append(f'pub const {name}: [i64; {len(v)}] = {v};')
        else:
            lines.append(f'pub const {name}: i64 = {v};')
lines.append(f'pub const FX_TOKENS: usize = {rules["fxTokens"]};')
rust = '\n'.join(lines) + '\n'

# ---- tooltips
g, b, s, u, p = rules['ghost'], rules['bulwark'], rules['bash'], rules['ult'], rules['passive']
a, au = rules['unarmed'], rules['aura']
sec = lambda t: f'{t / 60:g} s'
text = {
    'name': rules['name'],
    'skill': (f"Iron Ghost: becomes grey smoke for {sec(g['ticks'])}: untargetable and takes no damage, moving up to {g['maxDistance']} at +{g['ghostSpeedPct']}% speed; "
              f"recast to reappear early. Then +{g['tailSpeedPct']}% move speed fading over {sec(g['tailTicks'])}. Cleanses crowd control on cast "
              f"(cooldown {sec(g['cleanseCooldownTicks'])} if it cleansed, else {sec(g['cooldownTicks'])}). Reappearing within {g['resetRange']} of an enemy cuts {sec(g['resetTicks'])} off Skull Bash. "
              f"Passive Bloodrage: +{p['perMissingPctDamage'] / 100:g}% damage and +{p['perMissingPctMove'] / 100:g}% move speed per 1% missing HP, capped at {p['floorHpPct']}% HP. "
              f"Basic attacks deal +{rules['basic']['bruiserBonusPct']}% to knocked-up or stunned enemies."),
    'skill2': (f"Stone Bulwark ({sec(b['cooldownTicks'])}): a fissure {b['length']} long after {sec(b['castTicks'])} preparation, advancing over {sec(b['fissureTicks'])}: {b['base']} + {b['ratio']}% Attack and {b['slowPct']}% slow for {sec(b['slowTicks'])}. "
               f"After a further {sec(b['pillarDelayTicks'])}, a rock pillar rises at its end for {sec(b['pillarTicks'])}, a wall for everyone, nudging enemies within {b['nudgeRadius']} back {b['nudgeDistance']}. Recast once to move the pillar up to {b['relocateRange']} away, leaving a fissure trail that slows {b['trailSlowPct']}%. "
               f"Skull Bash ({sec(s['cooldownTicks'])}): charges up to {s['range']}; the first enemy takes {s['base']} + {s['ratio']}% Attack, is knocked back {s['knockback']} and stunned {sec(s['landStunTicks'])}. "
               f"Into a wall: {s['slamBase']} + {s['slamRatio']}% Attack and {sec(s['slamStunTicks'])} stun. Hitting the pillar (an enemy knocked into it, or Grimhald himself) shatters it: "
               f"{b['shatterBase']} + {b['shatterRatio']}% Attack and {sec(b['shatterTicks'])} knock-up in {b['shatterRadius']}."),
    'ult': (f"Warden's Verdict ({sec(u['cooldownTicks'])}): throws his axe up to {u['range']} (half the map), with at most {u['curveMilliDegrees']/1000:g} degrees of total steering. Landing: {u['base']} + {u['ratio']}% Attack and {sec(u['knockTicks'])} knock-up in {u['knockRadius']}. "
            f"If it knocked anyone up, a pentagon wall ({u['cageRadius']}) rises around the axe and he leaps into it: for {sec(u['cageTicks'])} every champion inside is caged. "
            f"They can attack and cast, but nothing takes them out and nobody gets in; inside sees only inside. If it hits nobody, the axe returns. "
            f"In the cage the axe stays planted at the centre and he fights unarmed: +{a['damagePct']}% damage, +{a['attackSpeedPct']}% attack speed, {a['lifestealPct']}% lifesteal and {a['damageReductionPct']}% damage reduction; each punch knocks back {a['punchKnockback']}. "
            f"Enemies inside lose {au['armourShredPct']}% armour and magic resistance and are slowed {au['slowPct']}%. Each kill while unarmed adds {sec(a['killBonusTicks'])} to the buff and the axe's aura (the cage falls on time)."),
}

# ---- champion data (Contender's never() shell)
champ = copy.deepcopy(json.loads((ROOT / 'mods/tfm2_custom/champion/tfm2_custom_contender.data_champion').read_text()))
champ.update(id=ID, category=rules['category'], tags=rules['tags'], sprite='asset/tfm2_custom/champions/' + ID, anim_prefix='')
for key in ['stat', 'growth']:
    champ[key] = {k: 0 for k in champ[key]}
    champ[key].update(rules[key])
champ['attack'].update(duration=20, cooltime=rules['basic']['cooldownTicks'], start_timing=10, range=rules['basic']['range'],
                       effect={'type': 'Attack', 'damage': 0, 'attack_ratio': 100})
for slot in ['skill', 'skill2', 'ult']:
    champ[slot]['description'] = '#asset/base/text/champion?description.' + ID + '.' + slot
champ['passive'] = {'passive_ref': 'tfm2_custom_ai:grimhald', 'params': {}}
champ['passive_ult'] = {'passive_ref': 'tfm2_custom_ai:ult_learned', 'params': {}}
VFX = 'asset/tfm2_custom/vfx/grimhald'
effects = ['axe_p' + str(i) for i in range(8)] + ['ult_marker', 'slash', 'slash_l', 'land', 'cage_block', 'cage_rise', 'fissure', 'pillar', 'pillar_rise',
           'pillar_break', 'trail', 'bash_dust', 'slam', 'ghost', 'ghost_end', 'leap'] + ['cage_phase'+str(i) for i in range(4)] + ['trail_d'+str(a)+'_l'+str(n) for a in range(rules['presentation']['trailDirections']) for n in range(1,rules['presentation']['trailMaxSteps']+1)]
effects += ['fissure_d'+str(i) for i in range(rules['presentation']['trailDirections'])]+['axe_planted']
champ['view_effects'] = [dict(type='Animation', name='grh_' + t, anim=VFX, tag=t, z=-2 if t in ('fissure', 'trail', 'land') or t.startswith(('trail_d','fissure_d')) else 5,
                              is_follow=False) for t in effects]
champ['view_buffs'] = [dict(type='Animated', name='grh_rage' + str(i), anim=VFX, tag='rage' + str(i), z=-1) for i in (1, 2, 3)]
champ['view_projectiles'] = []
data = json.dumps(champ, indent=2) + '\n'

# ---- roster entry
roster = dict(id=ID, name=rules['name'], family='original', role='Melee', native=True,
              basicAttack=dict(name='Axe swing', kind='melee', range=rules['basic']['range']),
              skills=[dict(slot='skill', name='Iron Ghost', kinds=['Blink', 'Buff'], intents=['Escape', 'Engage'], summary=text['skill']),
                      dict(slot='skill2', name='Stone Bulwark / Skull Bash', kinds=['Line', 'Dash', 'Cc'],
                           intents=['Clear', 'Engage', 'Protect', 'Objective'], summary=text['skill2']),
                      dict(slot='ult', name="Warden's Verdict", kinds=['Projectile', 'Cc', 'Dash'], intents=['Engage'], summary=text['ult'])])

outputs = {
    ROOT / 'editor/grimhald-data.js': 'window.GRIMHALD_RULES = '+json.dumps(rules,separators=(',',':'))+';\n',
    ROOT / 'native/tfm2_custom_ai/src/grimhald_data.rs': rust,
    ROOT / 'mods/tfm2_custom/champion' / f'{ID}.data_champion': data,
}
art=json.loads((ROOT/'rules/grimhald-art.json').read_text())
body_lines=['//! Generated from rules/grimhald-art.json.','pub const WEAPON_PREFIX: &str = '+json.dumps(art['weaponPrefix'])+';',"pub fn durations(name:&str)-> &'static [u64] { match name {"]
for name,durations in art['frameMillis'].items():body_lines.append(json.dumps(name)+'=> &'+str(durations)+',')
body_lines.extend(['_=> &[180],','}}'])
outputs[ROOT/'native/tfm2_custom_ai/src/grimhald_body_data.rs']='\n'.join(body_lines)+'\n'
if art['integrated']:
    champ['passive']['params']['weapon_layer']=1
    for name,frames in art['frameMillis'].items():
        for face in ['r','l']:
            for index in range(len(frames)):
                tag=art['weaponPrefix']+name+'_'+face+str(index)
                champ['view_buffs'].append(dict(type='Animated',name=tag,anim='asset/tfm2_custom/vfx/grimhald_weapon',tag=tag,z=-1))
    outputs[ROOT/'mods/tfm2_custom/champion'/f'{ID}.data_champion']=json.dumps(champ,indent=2)+'\n'
check = '--check' in sys.argv
stale = [str(p) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
i18n = ROOT / 'mods/tfm2_custom/text/champion.i18n'
loc = json.loads(i18n.read_text(encoding='utf8'))
roster_p = ROOT / 'rules/champions.json'
r = json.loads(roster_p.read_text(encoding='utf8'))
if loc['en']['description'].get(ID) != text:
    stale.append(str(i18n))
if next((c for c in r['champions'] if c['id'] == ID), None) != roster:
    stale.append(str(roster_p))
if check:
    if stale:
        sys.exit('stale: ' + ', '.join(stale))
    print('Grimhald outputs are current')
    sys.exit(0)
for p, s in outputs.items():
    p.write_text(s)
loc['en']['description'][ID] = text
i18n.write_text(json.dumps(loc, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
r['champions'] = [c for c in r['champions'] if c['id'] != ID] + [roster]
roster_p.write_text(json.dumps(r, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
print('Grimhald data, tooltips and roster entry generated')
