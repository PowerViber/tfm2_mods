"""Generate Kagami's Rust tables, champion data, tooltips, editor data and roster entry from rules/kagami.json.

Change numbers in the rules file and rerun; never edit the outputs by hand. `--check` only verifies.
"""
from pathlib import Path
import copy, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'rules/kagami.json').read_text())
ID = rules['id']
GROUPS = ['basic', 'clone', 'swap', 'angel', 'selfSave', 'step', 'charm', 'mend', 'ult', 'ai']


def snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).upper()


lines = ['//! Generated by tools/generate-kagami.py from rules/kagami.json. Do not edit by hand.', '#![allow(dead_code)]', '',
         'pub const RULES_REVISION: &str = ' + json.dumps(rules['revision']) + ';',
         f'pub const MOD_POWER: [i32; 7] = {rules["modPower"]};']
for group in GROUPS:
    for k, v in rules[group].items():
        lines.append(f'pub const {snake(group)}_{snake(k)}: i64 = {v};')
lines.append(f'pub const FX_TOKENS: usize = {rules["fxTokens"]};')
rust = '\n'.join(lines) + '\n'

b, cl, sw, an, ss, st, ch, me, ul, _ = (rules[k] for k in GROUPS)
sec = lambda n: f'{n / 60:g} s'
text = {
    'name': rules['name'],
    'skill': (f"Reflection (passive): Kagami always has a mirror clone ({cl['hpPct']}% of her max HP, her Defence) with no time limit. It follows her within "
              f"{cl['range']}, shoots light shards for {cl['damagePct']}% of her damage, and casts its own Moonlit Mend ({cl['mendPct']}% heal) and Kindred Charm "
              f"on teammates near it. It never casts Mirror Step or the ult. When it dies, a new one appears at her side {sec(cl['respawnTicks'])} later. "
              f"Guardian Angel (passive, {sec(an['cooldownTicks'])}): dropping below {an['thresholdPct']}% HP knocks back enemies within {an['radius']} and shields her "
              f"for {an['shieldPctMaxHp']}% max HP ({sec(an['shieldTicks'])}). "
              f"Mirror Swap (passive, {sec(ss['cooldownTicks'])}): a hit that would drop her under {ss['triggerPct']}% HP with her clone alive holds her at 1 HP and "
              f"swaps her with the clone; she's sealed for {sec(ss['sealTicks'])}, then revives at {ss['revivePct']}% HP. "
              f"Every swap takes {sec(sw['lockTicks'])}: it locks on to both sides (nobody is rooted) and trades them wherever they are, then stuns enemies within "
              f"{sw['stunRadius']} of the clone's new spot for {sec(sw['stunTicks'])}. "
              f"Mirror Step ({sec(st['cooldownTicks'])}): on a teammate within {st['range']} of the clone, the teammate and the clone swap; on a point within "
              f"{st['range']} of her, the clone dashes there and she swaps with it. A cancelled swap refunds {sw['refundPct']}% of the cooldown."),
    'skill2': (f"Kindred Charm ({sec(ch['cooldownTicks'])}): a teammate within {ch['range']} gets +{ch['attackSpeedPct']}% attack speed, +{ch['moveSpeedPct']}% "
               f"move speed and +{ch['damagePct']}% Attack and Magic Power for {sec(ch['ticks'])}. Her clone casts its own."),
    'ult': (f"Moonlit Mend ({sec(me['cooldownTicks'])}): heals a teammate within {me['range']} (or herself) for {me['base']} + {me['adRatio']}% Attack. "
            f"Last Reflection (ultimate, automatic, global, {sec(ul['cooldownTicks'])}): while it's ready every teammate but her is warded. The first one "
            f"who'd drop under {ul['triggerPct']}% HP is sealed for {sec(ul['sealTicks'])} (untargetable, unseen, unable to act), then revives at full HP with "
            f"Kindred Charm's buff, a shield of {ul['shieldPctMaxHp']}% max HP, +{ul['defencePct']}% Defence and crowd-control immunity for {sec(ul['reviveTicks'])}."),
}

champ = copy.deepcopy(json.loads((ROOT / 'mods/tfm2_custom/champion/tfm2_custom_contender.data_champion').read_text()))
# placeholder body until Codex's art: Thalassa's sheet (an original ranged caster) and her bolt
sprite = 'asset/tfm2_custom/champions/' + ID
if not (ROOT / f'mods/tfm2_custom/champions/{ID}#sheet.png').exists():
    sprite = 'asset/tfm2_custom/champions/tfm2_custom_thalassa'
champ.update(id=ID, category=rules['category'], tags=rules['tags'], sprite=sprite, anim_prefix='')
for key in ['stat', 'growth']:
    champ[key] = {k: 0 for k in champ[key]}
    champ[key].update(rules[key])
champ['attack'].update(duration=b['duration'], cooltime=b['cooldownTicks'], start_timing=b['startTiming'], range=b['range'],
                       effect={'type': 'TargetProjectile', 'speed': b['boltSpeed'], 'name': ID + '_shard', 'y_offset': 0, 'applied_target': 'Enemy',
                               'applied_effects': [{'effect': {'type': 'Attack', 'damage': 0, 'attack_ratio': 100}, 'casting_type': 'Targeting'}]})
for slot in ['skill', 'skill2', 'ult']:
    champ[slot]['description'] = '#asset/base/text/champion?description.' + ID + '.' + slot
champ['passive'] = {'passive_ref': 'tfm2_custom_ai:kagami', 'params': {}}
champ['passive_ult'] = {'passive_ref': 'tfm2_custom_ai:ult_learned', 'params': {}}
VFX = 'asset/tfm2_custom/vfx/kagami'
if (ROOT / 'mods/tfm2_custom/vfx/kagami#sheet.png').exists():
    champ['view_projectiles'] = [dict(type='Animated', name=ID + '_shard', anim=VFX, tag='shard', z=2, repeat=True)]
else:
    champ['view_projectiles'] = [dict(type='Animated', name=ID + '_shard', anim='asset/tfm2_custom/vfx/thalassa', tag='bolt', z=2, repeat=True)]
# her own effects arrive with Codex's sheet (`docs/kagami-art-handoff.md`); until then every name she plays is bound to
# Thalassa's existing sheet so the swaps, seals and heals are visible in a playtest
PLACEHOLDER = {'swap': 'swap', 'stun_burst': 'surge', 'seal': 'rescue', 'revive': 'trident_land', 'angel': 'bounce', 'clone_in': 'twin_spawn',
               'charm': 'dive_out', 'heal': 'pool_rise', 'shard_hit': 'bump', 'thread': 'tide_link'}
if (ROOT / 'mods/tfm2_custom/vfx/kagami#sheet.png').exists():
    champ['view_effects'] = [dict(type='Animation', name='kg_' + e, anim=VFX, tag=e, z=5, is_follow=False) for e in PLACEHOLDER]
    champ['view_buffs'] = [dict(type='Animated', name=n, anim=VFX, tag=n[3:], z=4) for n in ('kg_sealed', 'kg_charm', 'kg_revived')]
else:
    TLS = 'asset/tfm2_custom/vfx/thalassa'
    champ['view_effects'] = [dict(type='Animation', name='kg_' + e, anim=TLS, tag=tag, z=-2 if e == 'thread' else 5, is_follow=False) for e, tag in PLACEHOLDER.items()]
    champ['view_buffs'] = [dict(type='Animated', name=n, anim=TLS, tag='rescue_shield', z=4) for n in ('kg_sealed', 'kg_revived')]

data = json.dumps(champ, indent=2) + '\n'

roster = dict(id=ID, name=rules['name'], family='original', role='Support', native=True,
              basicAttack=dict(name='Mirror Shard', kind='ranged', range=b['range']),
              skills=[dict(slot='skill', name='Reflection / Guardian Angel / Mirror Swap / Mirror Step', kinds=['Summon', 'Blink', 'Cc', 'Shield'],
                           intents=['Protect', 'Escape', 'Engage'], summary=text['skill']),
                      dict(slot='skill2', name='Kindred Charm', kinds=['Buff'], intents=['Protect', 'Engage'], summary=text['skill2']),
                      dict(slot='ult', name='Moonlit Mend / Last Reflection', kinds=['Heal', 'Shield', 'Buff'], intents=['Protect'], summary=text['ult'])])

outputs = {
    ROOT / 'editor/kagami-data.js': 'window.KAGAMI_RULES = ' + json.dumps(rules, separators=(',', ':')) + ';\n',
    ROOT / 'native/tfm2_custom_ai/src/kagami_data.rs': rust,
    ROOT / 'mods/tfm2_custom/champion' / f'{ID}.data_champion': data,
}
check = '--check' in sys.argv
stale = [str(p) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
i18n = ROOT / 'mods/tfm2_custom/text/champion.i18n'
loc = json.loads(i18n.read_text(encoding='utf8'))
roster_p = ROOT / 'rules/champions.json'
r = json.loads(roster_p.read_text(encoding='utf8'))
if loc['en']['description'].get(ID) != text:
    stale.append(str(i18n))
if next((c for c in r['champions'] if c['id'] == ID), None) != roster:
    stale.append(str(roster_p))
if check:
    if stale:
        sys.exit('stale: ' + ', '.join(stale))
    print('Kagami outputs are current')
    sys.exit(0)
for p_, s in outputs.items():
    p_.write_text(s)
loc['en']['description'][ID] = text
i18n.write_text(json.dumps(loc, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
existing = [c['id'] for c in r['champions']]
if ID in existing:
    r['champions'] = [roster if c['id'] == ID else c for c in r['champions']]
else:
    r['champions'].append(roster)
roster_p.write_text(json.dumps(r, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
print('Kagami data, tooltips, editor data and roster entry generated')
