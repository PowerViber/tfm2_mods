"""Canonical catalogue -> Rust tables, Rift Lab data and the reviewer-friendly catalogue.

Run `python generate.py` after editing catalogue.json; `--check` verifies the generated files are current.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
DATA = json.loads((HERE / 'catalogue.json').read_text(encoding='utf-8'))


def validate():
    d = DATA
    assert len(d['families']) == 10 and len(d['dimensions']) == 100
    assert len(d['twists']) == 55 and len(d['rifts']) == 10 and len(d['techniques']) == 28
    assert len({x['name'] for x in d['dimensions']}) == 100
    prims = {p['id']: i for i, p in enumerate(d['prims'])}
    for i, x in enumerate(d['dimensions']):
        assert x['family'] == i // 10 and 0 <= x['prim'] < len(prims)
    pairs = {tuple(t['families']) for t in d['twists']}
    assert pairs == {(a, b) for a in range(10) for b in range(a, 10)}
    rift_ids = [r['id'] for r in d['rifts']]
    for t in d['techniques']:
        assert t['rifts'] and all(r in rift_ids for r in t['rifts'])
    for name, row in d['tables'].items():
        assert len(row) == 8, name
    tech_ids = [t['id'] for t in d['techniques']]
    for c in d['combos']:
        assert 1 <= len(c) <= 5 and all(s in tech_ids for s in c)
    return prims


def rust():
    d = DATA
    q = lambda x: json.dumps(x, ensure_ascii=True)
    out = ['// Generated by Claude outputs/vesper/generate.py from catalogue.json. Do not edit.',
           '#![allow(dead_code)]']
    for k, v in d['constants'].items():
        out.append(f'pub const {k.upper()}: i64 = {v};')
    out.append('pub const RANKS: [&str; 8] = [' + ', '.join(map(q, d['ranks'])) + '];')
    out.append(f"pub const TOP_NAME: &str = {q(d['top_name'])};")
    for name, row in d['tables'].items():
        out.append(f'pub const {name.upper()}: [i64; 8] = {row};')
    for name, rank in d['gates'].items():
        out.append(f'pub const GATE_{name.upper()}: usize = {rank};')
    out.append('pub const PRIM_IDS: [&str; %d] = [' % len(d['prims']) + ', '.join(q(p['id']) for p in d['prims']) + '];')
    for i, p in enumerate(d['prims']):
        out.append(f"pub const P_{p['id']}: u8 = {i};")
    out.append('/// Side: b\'E\' enemy, b\'A\' ally, b\'S\' Vesper, b\'P\' packet only, b\'X\' special.')
    out.append('pub const PRIM_SIDE: [u8; %d] = [' % len(d['prims']) + ', '.join(f"b'{p['side']}'" for p in d['prims']) + '];')
    out.append('pub const PRIM_ONCE: [bool; %d] = [' % len(d['prims']) + ', '.join('true' if p['once'] else 'false' for p in d['prims']) + '];')
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct Family { pub name: &'static str, pub aspect: usize, pub color: &'static str }")
    out.append('pub const FAMILIES: [Family; 10] = [' + ', '.join(
        f"Family {{ name: {q(f['name'])}, aspect: {f['aspect']}, color: {q(f['color'])} }}" for f in d['families']) + '];')
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct Dim { pub id: &'static str, pub name: &'static str, pub family: usize, pub prim: u8, pub a: i64, pub b: i64, pub c: i64 }")
    out.append('pub const DIMS: [Dim; 100] = [')
    for x in d['dimensions']:
        out.append(f"    Dim {{ id: {q(x['id'])}, name: {q(x['name'])}, family: {x['family']}, prim: {x['prim']}, a: {x['a']}, b: {x['b']}, c: {x['c']} }},")
    out.append('];')
    out.append('pub const TWIST_KINDS: [(&str, i64); %d] = [' % len(d['twist_kinds']) + ', '.join(
        f"({q(k['name'])}, {k['mag']})" for k in d['twist_kinds']) + '];')
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct Twist { pub name: &'static str, pub a: usize, pub b: usize, pub kind: usize, pub mag: i64 }")
    out.append('pub const TWISTS: [Twist; 55] = [')
    for t in d['twists']:
        out.append(f"    Twist {{ name: {q(t['name'])}, a: {t['families'][0]}, b: {t['families'][1]}, kind: {t['kind']}, mag: {t['mag']} }},")
    out.append('];')
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct RiftType { pub id: &'static str, pub name: &'static str, pub cost: usize, pub life: usize, pub radius: i64, pub length: i64, pub delay_pct: i64 }")
    out.append('pub const RIFTS: [RiftType; 10] = [' + ', '.join(
        f"RiftType {{ id: {q(r['id'])}, name: {q(r['name'])}, cost: {r['cost']}, life: {r['life']}, radius: {r['radius']}, length: {r['length']}, delay_pct: {r['delay_pct']} }}"
        for r in d['rifts']) + '];')
    rid = {r['id']: i for i, r in enumerate(d['rifts'])}
    for i, r in enumerate(d['rifts']):
        out.append(f"pub const R_{r['id'].upper()}: usize = {i};")
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct Tech { pub id: &'static str, pub name: &'static str, pub group: &'static str, pub rifts: &'static [usize], pub strain: i64, pub cooldown: usize }")
    out.append('pub const TECHS: [Tech; 28] = [')
    for t in d['techniques']:
        out.append(f"    Tech {{ id: {q(t['id'])}, name: {q(t['name'])}, group: {q(t['group'])}, rifts: &{[rid[r] for r in t['rifts']]}, strain: {t['strain']}, cooldown: {t['cooldown']} }},")
    out.append('];')
    tid = {t['id']: i for i, t in enumerate(d['techniques'])}
    for i, t in enumerate(d['techniques']):
        out.append(f"pub const T_{t['id'].upper()}: usize = {i};")
    out.append('pub const COMBOS: [&[usize]; %d] = [' % len(d['combos']) + ', '.join(
        '&' + str([tid[s] for s in c]) for c in d['combos']) + '];')
    return '\n'.join(out) + '\n'


def js():
    return ('// Generated by Claude outputs/vesper/generate.py. Canonical source: catalogue.json\n'
            '(function (root) { const data = ' + json.dumps(DATA, separators=(',', ':'), ensure_ascii=True) +
            '; if (typeof module !== "undefined") module.exports = data; else root.RiftData = data; })'
            '(typeof globalThis !== "undefined" ? globalThis : this);\n')


def markdown():
    d = DATA
    fam = [f['name'] for f in d['families']]
    prims = d['prims']
    md = ['# Vesper, the Rift Marksman: catalogue', '',
          'Generated from `Claude outputs/vesper/catalogue.json`. Everything here is available at every mastery rank; '
          'rank only changes how well the athlete plans with it.', '',
          '## Rift types', '', '| Rift | Charges | Life (ticks) | Size | What the shape does |', '|---|---|---|---|---|']
    for r in d['rifts']:
        size = f"r{r['radius']}" + (f", length {r['length']}" if r['length'] else '')
        md.append(f"| {r['name']} | {r['cost']} | {r['life']} | {size} | {r['text']} |")
    md += ['', '## Techniques', '', '| Technique | Group | Rifts | Strain | Per-target cooldown | What happens |', '|---|---|---|---|---|---|']
    names = {r['id']: r['name'] for r in d['rifts']}
    for t in d['techniques']:
        md.append(f"| {t['name']} | {t['group']} | {', '.join(names[r] for r in t['rifts'])} | {t['strain']} | {t['cooldown']} | {t['text']} |")
    md += ['', '## Dimensions', '', '| ID | Dimension | Family | Effect | Numbers |', '|---|---|---|---|---|']
    for x in d['dimensions']:
        p = prims[x['prim']]
        md.append(f"| {x['id']} | {x['name']} | {fam[x['family']]} | {p['id']}: {p['text']} | a={x['a']} b={x['b']} c={x['c']} |")
    md += ['', '## Family-pair bonuses (exit twists)', '', '| Families | Bonus | Effect | Strength |', '|---|---|---|---|']
    kinds = d['twist_kinds']
    for t in d['twists']:
        md.append(f"| {fam[t['families'][0]]} + {fam[t['families'][1]]} | {t['name']} | {kinds[t['kind']]['text']} | {t['mag']} |")
    md += ['', '## Ranks', '']
    for i, (r, h) in enumerate(zip(d['ranks'], d['habits'])):
        md.append(f"{i}. **{r}**: {h}")
    md.append(f"\nThe #1 athlete of the Top 10 is shown as **{d['top_name']}** (rank 7 brain, visuals only).")
    return '\n'.join(md) + '\n'


def generate(check=False):
    validate()
    outputs = {'native/tfm2_custom_ai/src/vesper_data.rs': rust(), 'editor/vesper-data.js': js(), 'docs/vesper-catalogue.md': markdown()}
    for path, content in outputs.items():
        p = ROOT / path
        if check:
            assert p.read_text(encoding='utf-8') == content, f'Stale generated file: {p}'
        else:
            tmp = p.with_name(p.name + '.tmp')
            tmp.write_text(content, encoding='utf-8', newline='\n')
            tmp.replace(p)
    print('Vesper catalogue current' if check else 'Generated Vesper data: 100 dimensions, 55 bonuses, 10 rift types, 28 techniques')


if __name__ == '__main__':
    import sys
    generate('--check' in sys.argv)
