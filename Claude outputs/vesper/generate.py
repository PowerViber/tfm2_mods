"""Canonical catalogue -> Rust tables, Rift Lab data and the reviewer-friendly catalogue.

Run `python generate.py` after editing catalogue.json; `--check` verifies the generated files are current.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
DATA = json.loads((HERE / 'catalogue.json').read_text(encoding='utf-8'))

# Release B: every dimension has a cooldown, classed by its rift's main effect (a `"cooldown"` entry overrides it;
# a spectacular dimension takes the signature class).
CD_CLASSES = {
    'light': ('Light utility', ['SLOW', 'HASTE', 'STATUP', 'STATDOWN', 'RANGE', 'MARK', 'SCRAMBLE', 'CDUP', 'CDDOWN', 'BADR', 'HEALCUT', 'VENT']),
    'damage': ('Damage', ['AMPLIFY', 'DOT', 'TRUE', 'EXECUTE', 'ECHO', 'WILDECHO', 'PRISM', 'SPLASH', 'RICOCHET', 'LENS', 'DRAIN', 'ENTROPY',
                          'SHATTER', 'COINFLIP', 'DICE', 'UNSTABLE', 'KALEIDO', 'CHAIN', 'REFLECTDMG', 'VAMP']),
    'strong': ('Strong control / support', ['BANISH', 'STUN', 'ROOT', 'SILENCE', 'DISARM', 'STATICBURST', 'ENCASE', 'WALLSLAM', 'HEAL', 'SHIELD',
                                            'SHELTER', 'UNDYING', 'CCIMMUNE', 'CLEANSE', 'ALLYINVIS', 'SELFINVIS', 'GHOST', 'SIPHON', 'TITHE',
                                            'RECALLHP', 'WALL']),
    'move': ('Teleport / displacement', ['PULL', 'KNOCK', 'SHOVE', 'STORM', 'GRAB', 'SWAPSPACE', 'SELFSWAP', 'BLINK', 'FOLD', 'REWIND', 'TOEND',
                                         'REFLECT', 'TETHER']),
}


def cd_class(x):
    if 'cooldown' in x:
        return 'custom'
    if x.get('spectacular'):
        return 'signature'
    pid = DATA['prims'][x['prim']]['id']
    return next(k for k, (_, prims) in CD_CLASSES.items() if pid in prims)


def cooldown(x):
    k = cd_class(x)
    return x['cooldown'] if k == 'custom' else DATA['constants'][f'cd_{k}']


for _x in DATA['dimensions']:
    _x['cd'] = cooldown(_x)


def validate():
    d = DATA
    assert len(d['families']) == 10 and len(d['dimensions']) == 100
    assert len(d['twists']) == 55 and len(d['rifts']) == 10 and len(d['techniques']) == 28
    assert len({x['name'] for x in d['dimensions']}) == 100
    assert len(d['modules']) == 8 and len(d['moves']) == 6
    prims = {p['id']: i for i, p in enumerate(d['prims'])}
    behaviours = set()
    for i, x in enumerate(d['dimensions']):
        assert x['family'] == i // 10 and 0 <= x['prim'] < len(prims)
        behaviours.add(('zone', x['prim'], x['a'], x['b'], x['c']))
        for k in ('punch', 'swipe'):
            main, rider = x[k]['main'], x[k]['rider'] or []
            assert len(main) == 4 and 0 <= main[0] < len(prims) and (not rider or (len(rider) == 4 and rider[0] < len(prims)))
            behaviours.add((k, *main, *rider))
    # every dimension opens three different behaviours: 300 in all, no two the same
    assert len(behaviours) == 300, len(behaviours)
    classed = [p for _, (_, v) in CD_CLASSES.items() for p in v]
    assert len(classed) == len(set(classed)) and set(classed) <= set(prims), 'cooldown classes'
    for f in range(len(d['families'])):
        assert sum(1 for x in d['dimensions'] if x['family'] == f and x.get('spectacular')) == 1, f'family {f}: one spectacular dimension'
    pairs = {tuple(t['families']) for t in d['twists']}
    assert pairs == {(a, b) for a in range(10) for b in range(a, 10)}
    rift_ids = [r['id'] for r in d['rifts']]
    for t in d['techniques']:
        assert t['rifts'] and all(r in rift_ids for r in t['rifts'])
    for name, row in d['tables'].items():
        assert len(row) == 8, name
    tech_ids = [t['id'] for t in d['techniques']]
    for c in d['combos']:
        assert 1 <= len(c) <= 5 and all(s in tech_ids for s in c)
    return prims


def rust():
    d = DATA
    q = lambda x: json.dumps(x, ensure_ascii=True)
    out = ['// Generated by Claude outputs/vesper/generate.py from catalogue.json. Do not edit.',
           '#![allow(dead_code)]']
    for k, v in d['constants'].items():
        out.append(f'pub const {k.upper()}: i64 = {v};')
    out.append('pub const RANKS: [&str; 8] = [' + ', '.join(map(q, d['ranks'])) + '];')
    out.append(f"pub const TOP_NAME: &str = {q(d['top_name'])};")
    for name, row in d['tables'].items():
        out.append(f'pub const {name.upper()}: [i64; 8] = {row};')
    for name, rank in d['gates'].items():
        out.append(f'pub const GATE_{name.upper()}: usize = {rank};')
    out.append('pub const PRIM_IDS: [&str; %d] = [' % len(d['prims']) + ', '.join(q(p['id']) for p in d['prims']) + '];')
    for i, p in enumerate(d['prims']):
        out.append(f"pub const P_{p['id']}: u8 = {i};")
    out.append('/// Side: b\'E\' enemy, b\'A\' ally, b\'S\' Vesper, b\'P\' packet only, b\'X\' special.')
    out.append('pub const PRIM_SIDE: [u8; %d] = *b"%s";' % (len(d['prims']), ''.join(p['side'] for p in d['prims'])))
    out.append('pub const PRIM_ONCE: [bool; %d] = [' % len(d['prims']) + ', '.join('true' if p['once'] else 'false' for p in d['prims']) + '];')
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct Family { pub name: &'static str, pub aspect: usize, pub color: &'static str }")
    out.append('pub const FAMILIES: [Family; 10] = [' + ', '.join(
        f"Family {{ name: {q(f['name'])}, aspect: {f['aspect']}, color: {q(f['color'])} }}" for f in d['families']) + '];')
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct Dim { pub id: &'static str, pub name: &'static str, pub family: usize, pub prim: u8, pub a: i64, pub b: i64, pub c: i64, pub cooldown: usize }")
    out.append('pub const DIMS: [Dim; 100] = [')
    for x in d['dimensions']:
        out.append(f"    Dim {{ id: {q(x['id'])}, name: {q(x['name'])}, family: {x['family']}, prim: {x['prim']}, a: {x['a']}, b: {x['b']}, c: {x['c']}, cooldown: {x['cd']} }},")
    out.append('];')
    out.append('/// One effect: a primitive and its numbers. `NO_EFF.prim` (255) means none.')
    out.append('#[derive(Clone, Copy, Debug, PartialEq, Eq)]')
    out.append('pub struct Eff { pub prim: u8, pub a: i64, pub b: i64, pub c: i64 }')
    out.append('pub const NO_EFF: Eff = Eff { prim: 255, a: 0, b: 0, c: 0 };')
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append('pub struct Delivery { pub main: Eff, pub rider: Eff }')
    e = lambda v: f'Eff {{ prim: {v[0]}, a: {v[1]}, b: {v[2]}, c: {v[3]} }}' if v else 'NO_EFF'
    for k in ('punch', 'swipe'):
        out.append(f'pub const {k.upper()}: [Delivery; 100] = [')
        for x in d['dimensions']:
            out.append(f"    Delivery {{ main: {e(x[k]['main'])}, rider: {e(x[k]['rider'])} }},")
        out.append('];')
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct Module { pub id: &'static str, pub name: &'static str, pub a: i64, pub b: i64 }")
    out.append('pub const MODULES: [Module; 8] = [' + ', '.join(
        f"Module {{ id: {q(m['id'])}, name: {q(m['name'])}, a: {m['a']}, b: {m['b']} }}" for m in d['modules']) + '];')
    out.append('pub const MOVE_IDS: [&str; %d] = [' % len(d['moves']) + ', '.join(q(m['id']) for m in d['moves']) + '];')
    out.append('pub const MOVE_ORBS: [usize; %d] = [' % len(d['moves']) + ', '.join(str(m['orbs']) for m in d['moves']) + '];')
    for i, m in enumerate(d['moves']):
        out.append(f"pub const M_{m['id'].upper()}: usize = {28 + i};")
    out.append('/// Hexcore completion -> active hexorb slots.')
    out.append('pub const HEX_SLOTS: [(i64, usize); %d] = [' % len(d['hexcore']['slots']) + ', '.join(f'({a}, {b})' for a, b in d['hexcore']['slots']) + '];')
    out.append(f"pub const HEX_FAST_AT: i64 = {d['hexcore']['fast_at']};")
    out.append(f"pub const HEX_RADIUS_AT: i64 = {d['hexcore']['radius_at']};")
    out.append('pub const TWIST_KINDS: [(&str, i64); %d] = [' % len(d['twist_kinds']) + ', '.join(
        f"({q(k['name'])}, {k['mag']})" for k in d['twist_kinds']) + '];')
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct Twist { pub name: &'static str, pub a: usize, pub b: usize, pub kind: usize, pub mag: i64 }")
    out.append('pub const TWISTS: [Twist; 55] = [')
    for t in d['twists']:
        out.append(f"    Twist {{ name: {q(t['name'])}, a: {t['families'][0]}, b: {t['families'][1]}, kind: {t['kind']}, mag: {t['mag']} }},")
    out.append('];')
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct RiftType { pub id: &'static str, pub name: &'static str, pub cost: usize, pub life: usize, pub radius: i64, pub length: i64, pub delay_pct: i64 }")
    out.append('pub const RIFTS: [RiftType; 10] = [' + ', '.join(
        f"RiftType {{ id: {q(r['id'])}, name: {q(r['name'])}, cost: {r['cost']}, life: {r['life']}, radius: {r['radius']}, length: {r['length']}, delay_pct: {r['delay_pct']} }}"
        for r in d['rifts']) + '];')
    rid = {r['id']: i for i, r in enumerate(d['rifts'])}
    for i, r in enumerate(d['rifts']):
        out.append(f"pub const R_{r['id'].upper()}: usize = {i};")
    out.append('#[derive(Clone, Copy, Debug)]')
    out.append("pub struct Tech { pub id: &'static str, pub name: &'static str, pub group: &'static str, pub rifts: &'static [usize], pub stress: i64, pub cooldown: usize, pub orbs: usize }")
    out.append('pub const TECHS: [Tech; 28] = [')
    for t in d['techniques']:
        out.append(f"    Tech {{ id: {q(t['id'])}, name: {q(t['name'])}, group: {q(t['group'])}, rifts: &{[rid[r] for r in t['rifts']]}, stress: {t['stress']}, cooldown: {t['cooldown']}, orbs: {t['orbs']} }},")
    out.append('];')
    tid = {t['id']: i for i, t in enumerate(d['techniques'])}
    for i, t in enumerate(d['techniques']):
        out.append(f"pub const T_{t['id'].upper()}: usize = {i};")
    out.append('pub const COMBOS: [&[usize]; %d] = [' % len(d['combos']) + ', '.join(
        '&' + str([tid[s] for s in c]) for c in d['combos']) + '];')
    return '\n'.join(out) + '\n'


def js():
    return ('// Generated by Claude outputs/vesper/generate.py. Canonical source: catalogue.json\n'
            '(function (root) { const data = ' + json.dumps(DATA, separators=(',', ':'), ensure_ascii=True) +
            '; if (typeof module !== "undefined") module.exports = data; else root.RiftData = data; })'
            '(typeof globalThis !== "undefined" ? globalThis : this);\n')


def markdown():
    d = DATA
    fam = [f['name'] for f in d['families']]
    prims = d['prims']
    md = ['# Vesper, the Rift Gauntlets: catalogue', '',
          'Generated from `Claude outputs/vesper/catalogue.json`. Everything here is available at every mastery rank; '
          'rank only changes how well the athlete plans with it.', '',
          '## Gauntlet moves', '', '| Move | Orbs | What happens |', '|---|---|---|']
    for m in d['moves']:
        md.append(f"| {m['name']} | {m['orbs']} | {m['text']} |")
    md += ['', '## Hexcore tech modules', '', 'Each athlete\'s Hexcore carries 6 of these 8 (derived from the athlete, editable in the editor).', '',
           '| Module | Effect | a | b |', '|---|---|---|---|']
    for m in d['modules']:
        md.append(f"| {m['name']} | {m['text']} | {m['a']} | {m['b']} |")
    md += ['', '| Hexcore completion | Hexorb slots |', '|---|---|']
    for a, b in d['hexcore']['slots']:
        md.append(f'| {a}% | {b} |')
    md += ['', '## Rift types', '', '| Rift | Orbs | Life (ticks) | Size | What the shape does |', '|---|---|---|---|---|']
    for r in d['rifts']:
        size = f"r{r['radius']}" + (f", length {r['length']}" if r['length'] else '')
        md.append(f"| {r['name']} | {r['cost']} | {r['life']} | {size} | {r['text']} |")
    md += ['', '## Techniques', '', '| Technique | Group | Rifts | Stress | Per-target cooldown | What happens |', '|---|---|---|---|---|---|']
    names = {r['id']: r['name'] for r in d['rifts']}
    for t in d['techniques']:
        md.append(f"| {t['name']} | {t['group']} | {', '.join(names[r] for r in t['rifts'])} | {t['stress']} | {t['cooldown']} | {t['text']} |")
    num = lambda e: ' '.join(f'{k}={v}' for k, v in zip('abc', e[1:]) if v)
    show = lambda e: f"**{prims[e[0]]['id']}** {num(e)}".strip() if e else ''
    c = d['constants']
    md += ['', '## Cooldowns', '',
           f"Every dimension has its own cooldown once she casts it, and its family rests {c['family_recovery'] / 60:g} s. Both gauntlets share both. "
           'The rifts of one cast (both ends of a gate, every node one action opens) and a fused punch count as one cast. '
           'Pulses and fists already in flight finish normally.', '',
           '| Class | Cooldown | Main effects |', '|---|---|---|']
    for k, (label, ps) in CD_CLASSES.items():
        md.append(f"| {label} | {c['cd_' + k] / 60:g} s | {', '.join(ps)} |")
    md.append(f"| Signature (one spectacular dimension per family) | {c['cd_signature'] / 60:g} s | |")
    md += ['', '## Dimensions: rift zone, punch and swipe', '',
           'Any orb opens any of the 100 dimensions. The rift zone, the rift punch and the rift swipe each have their own behaviour (300 in all). '
           'The numbers carry the 0.10.48 scale: damage, hard control, heals and shields x0.8, radii x0.85, crowd-control immunity and Undying x0.75.', '',
           '| ID | Dimension | Family | Cooldown | Rift zone | Punch (hole) | Swipe (tear line) |', '|---|---|---|---|---|---|---|']
    for x in d['dimensions']:
        zone = [x['prim'], x['a'], x['b'], x['c']]
        dl = lambda k: ' + '.join(v for v in (show(x[k]['main']), show(x[k]['rider'])) if v)
        star = ' (signature)' if x.get('spectacular') else ''
        md.append(f"| {x['id']} | {x['name']} | {fam[x['family']]} | {x['cd'] / 60:g} s{star} | {show(zone)} | {dl('punch')} | {dl('swipe')} |")
    md += ['', '### Primitives', '', '| Primitive | Side | Meaning |', '|---|---|---|']
    for p in prims:
        md.append(f"| {p['id']} | {p['side']} | {p['text']} |")
    md += ['', '## Family-pair bonuses (orb combos)', '', 'Two orbs of different families spent within a second of each other trigger their pair\'s bonus.', '', '| Families | Bonus | Effect | Strength |', '|---|---|---|---|']
    kinds = d['twist_kinds']
    for t in d['twists']:
        md.append(f"| {fam[t['families'][0]]} + {fam[t['families'][1]]} | {t['name']} | {kinds[t['kind']]['text']} | {t['mag']} |")
    md += ['', '## Ranks', '']
    for i, (r, h) in enumerate(zip(d['ranks'], d['habits'])):
        md.append(f"{i}. **{r}**: {h}")
    md.append(f"\nThe #1 athlete of the Top 10 is shown as **{d['top_name']}** (rank 7 brain, visuals only).")
    return '\n'.join(md) + '\n'


def generate(check=False):
    validate()
    outputs = {'native/tfm2_custom_ai/src/vesper_data.rs': rust(), 'editor/vesper-data.js': js(), 'docs/vesper-catalogue.md': markdown()}
    for path, content in outputs.items():
        p = ROOT / path
        if check:
            assert p.read_text(encoding='utf-8') == content, f'Stale generated file: {p}'
        else:
            tmp = p.with_name(p.name + '.tmp')
            tmp.write_text(content, encoding='utf-8', newline='\n')
            tmp.replace(p)
    print('Vesper catalogue current' if check else 'Generated Vesper data: 100 dimensions x 3 deliveries, 55 bonuses, 10 rift types, 28 techniques, 6 moves, 8 modules')


if __name__ == '__main__':
    import sys
    generate('--check' in sys.argv)
